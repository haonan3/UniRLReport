#!/usr/bin/env python3
"""Render reported summaries without reconstructing unavailable raw experiments."""

import argparse
import csv
from decimal import Decimal
import hashlib
import io
import json
import os
from pathlib import Path
import sys
import tempfile

# Both caches must be writable, including in a restricted local checkout.
os.environ.setdefault("MPLCONFIGDIR", str(Path(tempfile.gettempdir()) / "unirl-mpl-cache"))
os.environ.setdefault("XDG_CACHE_HOME", str(Path(tempfile.gettempdir()) / "unirl-plot-cache"))

ROOT = Path(__file__).resolve().parents[2]
BUNDLE = ROOT / "artifacts/reported_results/2026-09-22"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def signed(value):
    return ("+" if Decimal(value) >= 0 else "") + value


def ratio(numerator, denominator, digits):
    return f"{Decimal(numerator) / Decimal(denominator):.{digits}f}"


def write(path, content):
    path.write_text(content, encoding="utf-8")


def load_evidence():
    data = json.loads((BUNDLE / "evidence.json").read_text(encoding="utf-8"))
    assert data["evidence_tier"] == "reported_summary_not_independently_verified"
    assert len(data["e2"]["seed_labels"]) == data["e2"]["training_seeds"] == 3
    for metric in data["e2"]["metrics"]:
        assert len(metric["seed_changes"]) in (0, 3)
        for field in ("base", "final", "absolute_change", "relative_change_percent"):
            if metric[field] is not None:
                assert Decimal(metric[field]).is_finite()
    for experiment in ("e3", "e5t"):
        for row in data[experiment]["rows"]:
            assert Decimal(row["seconds_per_iteration"]) > 0
    for source in data["sources"]:
        assert (BUNDLE / source["snapshot"]).is_file(), source["snapshot"]
    return data


def render_tex(data):
    metrics = {metric["id"]: metric for metric in data["e2"]["metrics"]}
    systems = {row["id"]: row for row in data["e3"]["rows"]}
    topologies = {row["id"]: row for row in data["e5t"]["rows"]}
    seconds = lambda row: row["seconds_per_iteration"]
    macros = {
        "ReportedHPSGain": metrics["hpsv3"]["absolute_change"],
        "ReportedHPSBase": metrics["hpsv3"]["base"],
        "ReportedHPSFinal": metrics["hpsv3"]["final"],
        "ReportedImageRewardGain": metrics["image_reward"]["absolute_change"],
        "ReportedPickScoreGain": metrics["pickscore"]["absolute_change"],
        "ReportedDiversityChange": metrics["lpips"]["relative_change_percent"] + r"\%",
        "ReportedCompositionChange": metrics["composition"]["relative_change_percent"] + r"\%",
        "ReportedNativeSpeedup": ratio(seconds(systems["verl_sdpa"]), seconds(systems["unirl"]), 2),
        "ReportedFAThreeSpeedup": ratio(seconds(systems["verl_fa3"]), seconds(systems["unirl"]), 2),
        "ReportedTopologySlowdown": ratio(seconds(topologies["separate"]), seconds(topologies["colocated"]), 3),
        "ReportedUniRLSeconds": seconds(systems["unirl"]),
        "ReportedSDPASeconds": seconds(systems["verl_sdpa"]),
        "ReportedFAThreeSeconds": seconds(systems["verl_fa3"]),
        "ReportedColocatedSeconds": seconds(topologies["colocated"]),
        "ReportedSeparateSeconds": seconds(topologies["separate"]),
    }
    macros.update({row["macro"]: row["value"] for row in data["exploratory"]})
    header = "% Generated by experiments/reported_results/generate.py from evidence.json.\n"
    header += "% Reported summaries; not independently verified against raw logs.\n"
    write(BUNDLE / "macros.tex", header + "".join(
        "\\newcommand{\\" + name + "}{" + value + "}\n"
        for name, value in macros.items()
    ))
    e2 = [header.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrr@{}}", r"\toprule",
          r"Metric & Base & Rollout 300 & $\Delta$ score & $\Delta$ relative \\", r"\midrule"]
    for metric in data["e2"]["metrics"]:
        absolute = "--" if metric["absolute_change"] is None else signed(metric["absolute_change"])
        relative = "--" if metric["relative_change_percent"] is None else signed(metric["relative_change_percent"]) + r"\%"
        e2.append(" & ".join([metric["name"], metric["base"] or "--", metric["final"] or "--", absolute, relative]) + r" \\")
    e2.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e2_table.tex", "\n".join(e2))
    systems_table = [header.rstrip(), r"\begin{tabularx}{\textwidth}{@{}lXrr@{}}", r"\toprule",
                     r"System & Configuration & s/iteration & samples/GPU-h \\", r"\midrule",
                     r"\multicolumn{4}{@{}l}{E3: native recipes, eight GPUs in total} \\"]
    for row in data["e3"]["rows"]:
        displayed_seconds = f"{Decimal(row['seconds_per_iteration']):.1f}"
        systems_table.append(" & ".join([row["system"], row["configuration"], displayed_seconds, row["samples_per_gpu_hour"]]) + r" \\")
    systems_table.extend([r"\midrule", r"\multicolumn{4}{@{}l}{E5-T: deployment regimes, eight GPUs in total} \\"])
    for row in data["e5t"]["rows"]:
        systems_table.append(" & ".join(["UniRL", row["configuration"], row["seconds_per_iteration"], "--"]) + r" \\")
    systems_table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "systems_table.tex", "\n".join(systems_table))
    return macros


def render_csv(data):
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(["experiment", "metric", "arm_or_seed", "rollout", "statistic", "value", "unit", "provenance_ids"])
    for metric in data["e2"]["metrics"]:
        source = ";".join(metric["source_ids"])
        for field, rollout, unit in [("base", 0, "score"), ("final", 300, "score"), ("absolute_change", 300, "score"), ("relative_change_percent", 300, "percent_relative_to_base")]:
            if metric[field] is not None:
                writer.writerow(["E2", metric["id"], "reported_aggregate", rollout, field, metric[field], unit, source])
        for seed, value in zip(data["e2"]["seed_labels"], metric["seed_changes"]):
            writer.writerow(["E2", metric["id"], "reported_seed_" + seed, 300, "change_from_base", value, metric["seed_change_unit"], source])
    early = data["e2"]["early_diversity"]
    for seed, value in zip(data["e2"]["seed_labels"], early["seed_relative_change_percent"]):
        writer.writerow(["E2", "lpips", "reported_seed_" + seed, early["rollout"], "change_from_base", value, "percent_relative_to_base", ";".join(early["source_ids"])])
    for experiment in ("e3", "e5t"):
        for row in data[experiment]["rows"]:
            writer.writerow([data[experiment]["experiment"], "iteration_time", row["id"], "", "reported_aggregate", row["seconds_per_iteration"], "seconds", ";".join(data[experiment]["source_ids"])])
            if "samples_per_gpu_hour" in row:
                writer.writerow([data[experiment]["experiment"], "throughput", row["id"], "", "reported_aggregate", row["samples_per_gpu_hour"], "samples_per_gpu_hour", ";".join(data[experiment]["source_ids"])])
    for row in data["exploratory"]:
        writer.writerow([row["experiment"], row["metric"], row["id"], "", "reported_exploratory", row["value"], "count" if row["id"] == "e4a_checks" else "score", ";".join(row["source_ids"])])
    write(BUNDLE / "reported_values.csv", stream.getvalue())


def render_figures(data):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    import numpy as np

    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 10,
        "axes.labelsize": 10, "axes.titlesize": 10.5,
        "xtick.labelsize": 9, "ytick.labelsize": 9,
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.edgecolor": "#626975", "axes.linewidth": 0.65,
        "pdf.fonttype": 42, "ps.fonttype": 42,
        "savefig.facecolor": "white", "figure.facecolor": "white",
    })
    figure_dir = BUNDLE / "figures"
    figure_dir.mkdir(exist_ok=True)

    def save(fig, name):
        # PDF timestamp fields are omitted so identical inputs regenerate bytes.
        fig.savefig(figure_dir / (name + ".pdf"), metadata={"Creator": "UniRL reported-results generator", "CreationDate": None, "ModDate": None})
        fig.savefig(figure_dir / (name + ".png"), dpi=200, metadata={"Software": "UniRL reported-results generator"})
        plt.close(fig)

    def grid(ax):
        ax.grid(axis="y", color="#d9dee6", linewidth=0.6)
        ax.set_axisbelow(True)
        ax.tick_params(width=0.6, length=3)

    metrics = {metric["id"]: metric for metric in data["e2"]["metrics"]}
    fig, axes = plt.subplots(1, 3, figsize=(7.25, 3.15))
    fig.subplots_adjust(left=0.082, right=0.986, bottom=0.265, top=0.77, wspace=0.42)
    config = [
        ("hpsv3", "(a) HPSv3", "Change from base (score)", (0, 10), [0, 2, 4, 6, 8, 10], "#256b9c", 3),
        ("composition", "(b) Composition", "Change from base (%)", (0, 65), [0, 20, 40, 60], "#5c57a4", 1),
        ("lpips", "(c) LPIPS diversity", "Change from base (%)", (-30, 0), [-30, -20, -10, 0], "#b65e2b", 2),
    ]
    for ax, (key, title, ylabel, limits, ticks, color, precision) in zip(axes, config):
        metric = metrics[key]
        points = list(map(float, metric["seed_changes"]))
        aggregate = float(metric["absolute_change"] or metric["relative_change_percent"])
        ax.axhline(aggregate, color="#525a65", linewidth=1, linestyle=(0, (4, 3)))
        ax.scatter(range(3), points, s=39, color=color, edgecolors="white", linewidths=0.6, zorder=3)
        for x, point in enumerate(points):
            ax.annotate(f"{point:+.{precision}f}", (x, point), xytext=(0, 8 if point >= 0 else -13), textcoords="offset points", ha="center", fontsize=8.2, color=color)
        ax.set(xlim=(-0.46, 2.46), ylim=limits, yticks=ticks, xticks=range(3), xticklabels=data["e2"]["seed_labels"])
        ax.set_title(title, loc="left", pad=10, fontweight="semibold")
        ax.set_ylabel(ylabel)
        ax.set_xlabel("Reported seed", labelpad=4)
        grid(ax)
    fig.suptitle("E2: external scores and diversity at rollout 300", x=0.082, ha="left", y=0.975, fontsize=12, fontweight="semibold")
    fig.text(0.082, 0.86, "Changes relative to the frozen base; three training seeds", fontsize=9.2, color="#525a65")
    fig.legend(handles=[Line2D([0], [0], color="#525a65", linestyle=(0, (4, 3)), linewidth=1, label="Reported aggregate")], loc="lower left", bbox_to_anchor=(0.073, 0.055), frameon=False, fontsize=8.4)
    fig.text(0.082, 0.028, "Summary reports as of 2026-09-22; seed IDs unverified; no raw-log audit.", fontsize=7.8, color="#626975")
    save(fig, "e2_quality_diversity")

    fig, axes = plt.subplots(1, 2, figsize=(7.25, 3.55), gridspec_kw={"width_ratios": [1.25, 1]})
    fig.subplots_adjust(left=0.082, right=0.982, bottom=0.27, top=0.78, wspace=0.31)
    setups = [
        (data["e3"]["rows"], ["UniRL\nflow", "VeRL-Omni\nCPS / SDPA", "VeRL-Omni\nCPS / FA3"], ["#256b9c", "#8e9aa8", "#b0bbc6"], "(a) E3: native recipes", 130, 1),
        (data["e5t"]["rows"], ["Colocated\n8 shared GPUs", "Separate\n4 train + 4 rollout"], ["#256b9c", "#b65e2b"], "(b) E5-T: deployment regimes", 170, 3),
    ]
    for ax, (rows, labels, colors, title, upper, precision) in zip(axes, setups):
        times = [float(row["seconds_per_iteration"]) for row in rows]
        ax.bar(range(len(rows)), times, width=0.61, color=colors, zorder=3)
        for x, row in enumerate(rows):
            displayed_seconds = f"{Decimal(row['seconds_per_iteration']):.{precision}f}"
            ax.text(x, float(row["seconds_per_iteration"]) + 3, displayed_seconds, ha="center", va="bottom", fontsize=9)
        ax.set(xticks=range(len(rows)), xticklabels=labels, ylim=(0, upper))
        ax.set_title(title, loc="left", pad=10, fontweight="semibold")
        ax.set_ylabel("Seconds per iteration")
        grid(ax)
    fig.suptitle("E3 and E5-T: reported iteration time", x=0.082, ha="left", y=0.975, fontsize=12, fontweight="semibold")
    fig.text(0.082, 0.875, "Eight GPUs in each configuration; lower is faster", fontsize=9.2, color="#525a65")
    fig.text(0.082, 0.105, "E3 changes native recipes; E5-T changes allocation and residency together.", fontsize=8.2, color="#525a65")
    fig.text(0.082, 0.045, "Reported aggregates only; no raw-log audit or uncertainty estimate.", fontsize=8, color="#626975")
    save(fig, "e3_e5_systems")
    return {"python": sys.version.split()[0], "matplotlib": matplotlib.__version__, "numpy": np.__version__}


def save_manifest(versions):
    files = sorted(path for path in BUNDLE.rglob("*") if path.is_file() and path.name not in ("manifest.json", "checksums.sha256"))
    hashes = {str(path.relative_to(BUNDLE)): digest(path) for path in files}
    generator = Path(__file__).resolve()
    manifest = {
        "schema_version": 1,
        "evidence_tier": "reported_summary_not_independently_verified",
        "report_as_of": "2026-09-22", "retrieved_on": "2026-09-27",
        "generator": str(generator.relative_to(ROOT)), "generator_sha256": digest(generator),
        "versions": versions,
        "reproduction": "python3 experiments/reported_results/generate.py",
        "note": "Hashes preserve this reported-summary bundle; they do not verify the underlying experiment runs.",
        "sha256": hashes,
    }
    write(BUNDLE / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    write(BUNDLE / "checksums.sha256", "".join(value + "  " + key + "\n" for key, value in hashes.items()))


def check():
    manifest = json.loads((BUNDLE / "manifest.json").read_text(encoding="utf-8"))
    mismatches = [name for name, expected in manifest["sha256"].items() if not (BUNDLE / name).is_file() or digest(BUNDLE / name) != expected]
    if digest(Path(__file__)) != manifest["generator_sha256"]:
        mismatches.append("generator")
    if mismatches:
        raise SystemExit("Checksum mismatch: " + ", ".join(mismatches))
    print(f"Verified {len(manifest['sha256'])} bundle files and generator hash.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the archived bundle hashes without regenerating it")
    args = parser.parse_args()
    if args.check:
        check()
        return
    data = load_evidence()
    macros = render_tex(data)
    render_csv(data)
    versions = render_figures(data)
    save_manifest(versions)
    print(f"Generated {len(macros)} macros, two tables, numeric CSV, two PDF figures, PNG previews, and checksums.")


if __name__ == "__main__":
    main()
