#!/usr/bin/env python3
"""Deterministic generator for the E5-R + E4a reported-results bundle.

Reads:
  - e5r_summary.csv
  - e5r_trials.csv
  - e5r_correctness.json
  - transport_*.json (if present)

Writes:
  - e5r_table.tex
  - macros.tex
  - figures/e5r_overhead.pdf
  - figures/e5r_overhead.png
  - README.md
  - checksums.sha256
"""

from __future__ import annotations

import csv
import hashlib
import json
import os
import tempfile
from pathlib import Path
from typing import Any, Dict, List

os.environ.setdefault("MPLCONFIGDIR", str(Path(tempfile.gettempdir()) / "unirl-mpl-cache"))
os.environ.setdefault("XDG_CACHE_HOME", str(Path(tempfile.gettempdir()) / "unirl-plot-cache"))

HERE = Path(__file__).resolve().parent
HEADER = (
    "% Generated by generate.py in this directory from e5r_summary.csv and e5r_correctness.json; "
    "do not edit by hand.\n"
)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_summary(path: Path) -> List[Dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _find(
    rows: List[Dict[str, str]],
    *,
    representation: str,
    backend: str,
    placement: str,
    roots: int,
    payload_mode: str,
) -> Dict[str, str]:
    for r in rows:
        if (
            r["representation"] == representation
            and r["backend"] == backend
            and r["placement"] == placement
            and int(r["roots"]) == roots
            and r["payload_mode"] == payload_mode
        ):
            return r
    raise KeyError(f"Missing row: {representation}, {backend}, {placement}, roots={roots}, payload={payload_mode}")


def write_e5r_table(rows: List[Dict[str, str]], out_path: Path) -> None:
    lines: List[str] = [
        HEADER,
        r"\begin{tabular}{@{}llrrlrrrrrrr@{}}",
        r"\toprule",
        r"Backend / Placement & Arm & $P$ & Leaves & Payload & Split & Select & Concat & Credit+Adv & Transport+Mat & Total (ms) & \% of E4 (29.2\,s / 64.2\,s) \\",
        r"\midrule",
    ]

    blocks = [
        ("colocate_store", "same_gpu", r"\texttt{colocate\_store}, same GPU", ["e4_exact", "1", "16", "64"]),
        ("colocate_store", "cross_gpu", r"\texttt{colocate\_store}, cross GPU (NVLink)", ["e4_exact", "16", "64"]),
        ("gpu_store", "same_gpu", r"\texttt{gpu\_store} (CUDA IPC), same GPU", ["e4_exact", "16", "64"]),
        ("gpu_store", "cross_gpu", r"\texttt{gpu\_store} (CUDA IPC), cross GPU", ["e4_exact", "16", "64"]),
    ]

    for b_idx, (backend, placement, title, payloads) in enumerate(blocks):
        if b_idx > 0:
            lines.append(r"\midrule")
        lines.append(rf"\multicolumn{{12}}{{@{{}}l}}{{\textbf{{{title}}}}} \\")
        for roots in (8, 32, 128):
            for pmode in payloads:
                if b_idx > 0 and roots == 32 and pmode == "16":
                    continue
                for rep in ("tree", "flat_id_join"):
                    r = _find(
                        rows,
                        representation=rep,
                        backend=backend,
                        placement=placement,
                        roots=roots,
                        payload_mode=pmode,
                    )
                    arm_label = r"\texttt{tree} (\texttt{Sample}+\texttt{TensorRef})" if rep == "tree" else r"\texttt{flat\_id\_join}"
                    plabel = "E4 (2.98\\,MiB)" if pmode == "e4_exact" else f"{pmode}\\,MiB"
                    split_ms = float(r["split_median_ms"])
                    sel_ms = float(r["select_median_ms"])
                    cat_ms = float(r["concat_median_ms"])
                    cred_ms = float(r["credit_and_advantage_median_ms"])
                    tr_mat_ms = float(r["handle_transport_median_ms"]) + float(r["materialize_median_ms"])
                    tot_ms = float(r["total_critical_path_median_ms"])
                    pct_29 = float(r["total_pct_of_e4v2_29_2s"])
                    pct_64 = float(r["total_pct_of_e4_64_2s"])
                    lines.append(
                        f" & {arm_label} & {roots} & {int(r['leaves'])} & {plabel} & "
                        f"{split_ms:.2f} & {sel_ms:.2f} & {cat_ms:.2f} & {cred_ms:.2f} & "
                        f"{tr_mat_ms:.2f} & {tot_ms:.2f} & {pct_29:.3f}\\% / {pct_64:.3f}\\% \\\\"
                    )

    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    out_path.write_text("\n".join(lines), encoding="utf-8")


def write_macros(rows: List[Dict[str, str]], corr: Dict[str, Any], out_path: Path) -> None:
    t_e4_same = _find(
        rows, representation="tree", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="e4_exact"
    )
    f_e4_same = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="e4_exact"
    )
    t_e4_cross = _find(
        rows, representation="tree", backend="colocate_store", placement="cross_gpu", roots=8, payload_mode="e4_exact"
    )
    f_e4_cross = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="cross_gpu", roots=8, payload_mode="e4_exact"
    )
    t_e4_ipc_same = _find(
        rows, representation="tree", backend="gpu_store", placement="same_gpu", roots=8, payload_mode="e4_exact"
    )
    t_e4_ipc_cross = _find(
        rows, representation="tree", backend="gpu_store", placement="cross_gpu", roots=8, payload_mode="e4_exact"
    )

    t_128_64_same = _find(
        rows, representation="tree", backend="colocate_store", placement="same_gpu", roots=128, payload_mode="64"
    )
    f_128_64_same = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="same_gpu", roots=128, payload_mode="64"
    )
    t_128_64_cross = _find(
        rows, representation="tree", backend="colocate_store", placement="cross_gpu", roots=128, payload_mode="64"
    )
    f_128_64_cross = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="cross_gpu", roots=128, payload_mode="64"
    )

    t_8_1_same = _find(
        rows, representation="tree", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="1"
    )
    t_8_64_same = _find(
        rows, representation="tree", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="64"
    )
    f_8_1_same = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="1"
    )
    f_8_64_same = _find(
        rows, representation="flat_id_join", backend="colocate_store", placement="same_gpu", roots=8, payload_mode="64"
    )

    macros = {
        "EFiveRRecordedRollouts": str(corr["e4a_recorded_rollout_verification"]["num_captures_verified"]),
        "EFiveRPairedCells": str(corr["e5r_paired_cell_verification"]["num_paired_cells"]),
        "EFiveRTreeEExactSameStructMs": f"{float(t_e4_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRTreeEExactSameTotalMs": f"{float(t_e4_same['total_critical_path_median_ms']):.2f}",
        "EFiveRFlatEExactSameStructMs": f"{float(f_e4_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRFlatEExactSameTotalMs": f"{float(f_e4_same['total_critical_path_median_ms']):.2f}",
        "EFiveRTreeEExactCrossTotalMs": f"{float(t_e4_cross['total_critical_path_median_ms']):.2f}",
        "EFiveRFlatEExactCrossTotalMs": f"{float(f_e4_cross['total_critical_path_median_ms']):.2f}",
        "EFiveRTreeEExactIPCSameTotalMs": f"{float(t_e4_ipc_same['total_critical_path_median_ms']):.2f}",
        "EFiveRTreeEExactIPCCrossTotalMs": f"{float(t_e4_ipc_cross['total_critical_path_median_ms']):.2f}",
        "EFiveRTreeEExactPctSixtyFour": f"{float(t_e4_same['total_pct_of_e4_64_2s']):.4f}\\%",
        "EFiveRTreeEExactPctTwentyNine": f"{float(t_e4_same['total_pct_of_e4v2_29_2s']):.4f}\\%",
        "EFiveRTreeEExactCrossPctSixtyFour": f"{float(t_e4_cross['total_pct_of_e4_64_2s']):.4f}\\%",
        "EFiveRTreeEExactCrossPctTwentyNine": f"{float(t_e4_cross['total_pct_of_e4v2_29_2s']):.4f}\\%",
        "EFiveRTreeEExactMetaKiB": f"{int(t_e4_same['metadata_bytes']) / 1024.0:.1f}",
        "EFiveRFlatEExactMetaKiB": f"{int(f_e4_same['metadata_bytes']) / 1024.0:.1f}",
        "EFiveRTreeEExactAvoidedMiB": f"{float(t_e4_same['dense_payload_mib']):.1f}",
        "EFiveRTreePOneTwoEightPSixFourSameStructMs": f"{float(t_128_64_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRTreePOneTwoEightPSixFourSameTotalMs": f"{float(t_128_64_same['total_critical_path_median_ms']):.2f}",
        "EFiveRFlatPOneTwoEightPSixFourSameStructMs": f"{float(f_128_64_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRFlatPOneTwoEightPSixFourSameTotalMs": f"{float(f_128_64_same['total_critical_path_median_ms']):.2f}",
        "EFiveRTreePOneTwoEightPSixFourCrossTotalMs": f"{float(t_128_64_cross['total_critical_path_median_ms']):.2f}",
        "EFiveRFlatPOneTwoEightPSixFourCrossTotalMs": f"{float(f_128_64_cross['total_critical_path_median_ms']):.2f}",
        "EFiveRTreePOneTwoEightPSixFourPctSixtyFour": f"{float(t_128_64_same['total_pct_of_e4_64_2s']):.3f}\\%",
        "EFiveRTreePOneTwoEightPSixFourPctTwentyNine": f"{float(t_128_64_same['total_pct_of_e4v2_29_2s']):.3f}\\%",
        "EFiveRTreePEightPOneStructMs": f"{float(t_8_1_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRTreePEightPSixFourStructMs": f"{float(t_8_64_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRFlatPEightPOneStructMs": f"{float(f_8_1_same['structure_critical_path_median_ms']):.2f}",
        "EFiveRFlatPEightPSixFourStructMs": f"{float(f_8_64_same['structure_critical_path_median_ms']):.2f}",
    }
    lines = [HEADER] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()] + [""]
    out_path.write_text("\n".join(lines), encoding="utf-8")


def write_figures(rows: List[Dict[str, str]], fig_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    fig_dir.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 8.8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.edgecolor": "#4a525d",
            "axes.linewidth": 0.7,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "savefig.facecolor": "white",
            "figure.facecolor": "white",
        }
    )

    fig, axes = plt.subplots(1, 3, figsize=(11.2, 3.2))
    c_tree = "#1f6f8b"
    c_flat = "#c85a32"

    # Panel (a): Total critical path (ms) vs Leaf Payload Size on same_gpu (colocate_store) for P=8, 32, 128
    ax = axes[0]
    payload_modes = ["1", "e4_exact", "16", "64"]
    x_pos = np.arange(len(payload_modes))
    x_labels = ["1 MiB", "E4\n(2.98 MiB)", "16 MiB", "64 MiB"]
    markers = {8: "o", 32: "s", 128: "^"}
    for roots in (8, 32, 128):
        y_tree = [
            float(
                _find(
                    rows,
                    representation="tree",
                    backend="colocate_store",
                    placement="same_gpu",
                    roots=roots,
                    payload_mode=pm,
                )["total_critical_path_median_ms"]
            )
            for pm in payload_modes
        ]
        y_flat = [
            float(
                _find(
                    rows,
                    representation="flat_id_join",
                    backend="colocate_store",
                    placement="same_gpu",
                    roots=roots,
                    payload_mode=pm,
                )["total_critical_path_median_ms"]
            )
            for pm in payload_modes
        ]
        ax.plot(
            x_pos,
            y_tree,
            marker=markers[roots],
            color=c_tree,
            linestyle="-",
            linewidth=1.5,
            markersize=5,
            label=f"tree (P={roots})" if roots in (8, 128) else None,
        )
        ax.plot(
            x_pos,
            y_flat,
            marker=markers[roots],
            color=c_flat,
            linestyle="--",
            linewidth=1.5,
            markersize=5,
            label=f"flat_id_join (P={roots})" if roots in (8, 128) else None,
        )
    ax.set_xticks(x_pos, x_labels)
    ax.set_ylabel("Total critical path median (ms)")
    ax.set_title("(a) Payload invariance on same GPU", loc="left", fontsize=9.3, fontweight="bold")
    ax.grid(axis="y", color="#dfe4ea", linewidth=0.6)
    ax.legend(frameon=False, fontsize=7.6, loc="upper left")

    # Panel (b): Operation breakdown at P=32 (1024 leaves), payload=64 MiB (64 GiB batch)
    ax = axes[1]
    configs = [
        ("tree", "colocate_store", "same_gpu", "tree\ncolocate\nsame"),
        ("flat_id_join", "colocate_store", "same_gpu", "flat\ncolocate\nsame"),
        ("tree", "colocate_store", "cross_gpu", "tree\ncolocate\ncross"),
        ("flat_id_join", "colocate_store", "cross_gpu", "flat\ncolocate\ncross"),
        ("tree", "gpu_store", "cross_gpu", "tree\ngpu_store\ncross"),
        ("flat_id_join", "gpu_store", "cross_gpu", "flat\ngpu_store\ncross"),
    ]
    ops = [
        ("split_median_ms", "split", "#2b5c8f"),
        ("select_median_ms", "select", "#388087"),
        ("concat_median_ms", "concat", "#6fb3b8"),
        ("credit_and_advantage_median_ms", "credit+adv", "#badfe7"),
        ("handle_transport_median_ms", "transport", "#e07a5f"),
        ("materialize_median_ms", "materialize", "#f2cc8f"),
    ]
    xb = np.arange(len(configs))
    bottoms = np.zeros(len(configs))
    for key, label, col in ops:
        vals = np.array(
            [
                float(
                    _find(
                        rows,
                        representation=rep,
                        backend=bk,
                        placement=pl,
                        roots=32,
                        payload_mode="64",
                    )[key]
                )
                for rep, bk, pl, _ in configs
            ]
        )
        ax.bar(xb, vals, bottom=bottoms, width=0.58, label=label, color=col, edgecolor="white", linewidth=0.4)
        bottoms += vals
    ax.set_xticks(xb, [c[3] for c in configs], fontsize=7.5)
    ax.set_ylabel("Median time (ms) at P=32, 64 MiB/leaf")
    ax.set_title("(b) Phase breakdown (64 GiB batch)", loc="left", fontsize=9.3, fontweight="bold")
    ax.grid(axis="y", color="#dfe4ea", linewidth=0.6)
    ax.legend(frameon=False, fontsize=7.4, ncol=2, loc="upper left")

    # Panel (c): Fraction of E4 step time (% of 29.2s E4 v2 actual step time) on E4 exact payload
    ax = axes[2]
    roots_arr = [8, 32, 128]
    xr = np.arange(len(roots_arr))
    w = 0.19
    series = [
        ("tree", "colocate_store", "same_gpu", "tree (same GPU)", "#1f6f8b"),
        ("flat_id_join", "colocate_store", "same_gpu", "flat (same GPU)", "#c85a32"),
        ("tree", "colocate_store", "cross_gpu", "tree (cross GPU)", "#4ea8de"),
        ("flat_id_join", "colocate_store", "cross_gpu", "flat (cross GPU)", "#e59866"),
    ]
    for idx, (rep, bk, pl, lbl, col) in enumerate(series):
        pcts = [
            float(
                _find(
                    rows,
                    representation=rep,
                    backend=bk,
                    placement=pl,
                    roots=r_val,
                    payload_mode="e4_exact",
                )["total_pct_of_e4v2_29_2s"]
            )
            for r_val in roots_arr
        ]
        ax.bar(xr + (idx - 1.5) * w, pcts, width=w, label=lbl, color=col)
    ax.set_xticks(xr, ["P=8\n(256 leaves)", "P=32\n(1024 leaves)", "P=128\n(4096 leaves)"])
    ax.set_ylabel("% of E4 v2 step time (29.2 s)")
    ax.set_title("(c) Overhead vs. E4 step time", loc="left", fontsize=9.3, fontweight="bold")
    ax.grid(axis="y", color="#dfe4ea", linewidth=0.6)
    ax.legend(frameon=False, fontsize=7.4, loc="upper left")

    fig.tight_layout()
    fig.savefig(
        fig_dir / "e5r_overhead.pdf",
        metadata={"Creator": "UniRL E5-R generator", "CreationDate": None, "ModDate": None},
    )
    fig.savefig(fig_dir / "e5r_overhead.png", dpi=200, metadata={"Software": "UniRL E5-R generator"})
    plt.close(fig)


def write_checksums(bundle_dir: Path) -> None:
    files = sorted(
        p
        for p in bundle_dir.rglob("*")
        if p.is_file() and p.name != "checksums.sha256" and "__pycache__" not in p.parts
    )
    lines = [f"{_sha256(p)}  {p.relative_to(bundle_dir)}" for p in files]
    (bundle_dir / "checksums.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    rows = _load_summary(HERE / "e5r_summary.csv")
    corr = json.loads((HERE / "e5r_correctness.json").read_text(encoding="utf-8"))
    write_e5r_table(rows, HERE / "e5r_table.tex")
    write_macros(rows, corr, HERE / "macros.tex")
    write_figures(rows, HERE / "figures")
    write_checksums(HERE)
    print(f"Generated e5r_table.tex, macros.tex, figures/e5r_overhead.{{pdf,png}}, checksums.sha256 in {HERE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
