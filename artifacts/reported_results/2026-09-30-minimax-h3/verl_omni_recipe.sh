    "+reward.reward_functions.clap.batch_size=2"
    "+reward.reward_functions.clap.model_name_or_path=$CONTROL_CLAP_MODEL_PATH"
    "reward.aggregation=weighted_sum"
    "trainer.logger=['console','wandb']"
    "trainer.project_name=$CONTROL_WANDB_PROJECT"
    "trainer.experiment_name=$CONTROL_EXPERIMENT_NAME"
    "trainer.default_local_dir=$CONTROL_OUTPUT_DIR/checkpoints"
    "trainer.validation_data_dir=null"
    "trainer.rollout_data_dir=$CONTROL_OUTPUT_DIR/rollout_data"
    "trainer.rollout_data_save_freq=1000"
    "trainer.rollout_data_max_samples=2"
    "trainer.video_fps=24"
    "trainer.val_before_train=False"
    "trainer.n_gpus_per_node=8"
    "trainer.nnodes=1"
    "trainer.save_freq=10"
    "trainer.max_actor_ckpt_to_keep=1"
    "trainer.test_freq=-1"
    "trainer.total_epochs=1000"
    "trainer.total_training_steps=1000"
    "trainer.use_v1=true"
    "trainer.v1.trainer_mode=sync"
  )
}
