    "actor_rollout_ref.rollout.algo.init_same_noise=False"
    "actor_rollout_ref.rollout.algo.trajectory_dtype=fp16"
    "actor_rollout_ref.rollout.algo.logprob_dtype=fp32"
    "reward.num_workers=8"
    "reward.reward_model.enable=False"
    "reward.custom_reward_function.path=pkg://verl_omni.reward_loop.reward_manager.multi"
    "reward.custom_reward_function.name=_multi_reward_placeholder"
    "reward.reward_manager.name=MultiVisualRewardManager"
    "reward.reward_manager.module.path=pkg://verl_omni.reward_loop.reward_manager"
    "+reward.reward_functions.imagebind.path=$CONTROL_REPO/verl_omni/utils/reward_score/imagebind.py"
    "+reward.reward_functions.imagebind.name=compute_score"
    "+reward.reward_functions.imagebind.weight=1.0"
    "+reward.reward_functions.imagebind.required=true"
    "+reward.reward_functions.imagebind.device=cpu"
