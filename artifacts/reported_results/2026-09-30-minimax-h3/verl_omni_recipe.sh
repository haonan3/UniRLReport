    "+reward.reward_functions.imagebind.model_name_or_path=$CONTROL_IMAGEBIND_MODEL_PATH"
    "+reward.reward_functions.imagebind.mode=audio_video"
    "+reward.reward_functions.clap.path=$CONTROL_REPO/verl_omni/utils/reward_score/clap.py"
