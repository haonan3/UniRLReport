def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, content):
    path.write_text(content, encoding="utf-8")


def fixed(value, digits, sign=False):
    # Fractions are rounded exactly, so a value on a rounding boundary does not depend on its float form.
    exact = Decimal(value.numerator) / Decimal(value.denominator) if isinstance(value, Fraction) else Decimal(repr(float(value)))
    text = str(exact.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_EVEN))
    return ("+" if sign and exact >= 0 else "") + text


def tex(text):
    return text.replace("-", "$-$", 1) if text.startswith("-") else text


def sci(value):
    mantissa, exponent = f"{value:.1e}".split("e")
    return f"${mantissa}\\times10^{{{int(exponent)}}}$"


def seed_interval(values):
    mean = statistics.fmean(values)
    half = T_975_DF2 * statistics.stdev(values) / math.sqrt(len(values))
    return mean, mean - half, mean + half


def quantile(values, q):
    ordered = sorted(values)
    position = q * (len(ordered) - 1)
    low = int(position)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (position - low)


def load_e1():
    evaluations = list(csv.DictReader((DATA / "e1_evaluations.csv").open(encoding="utf-8")))
    cells = {}
    for bench in ("math500", "aime24", "aime25"):
        rows = list(csv.DictReader((DATA / f"e1_scores_{bench}.csv").open(encoding="utf-8")))
        for record in (row for row in evaluations if row["benchmark"] == bench):
            k = int(record["samples_per_prompt"])
            scores = [Fraction(row[record["tag"]]) for row in rows]
            assert len(scores) == int(record["prompts"]) == int(record["prompts_scored"]) and record["errors"] == "0"
            variance = sum(score * (1 - score) for score in scores) / (k - 1) / len(scores) ** 2
            key = (record["objective"], record["seed"], int(record["rollout"]), bench)
            cells.setdefault(key, []).append({
                "acc": sum(scores) / len(scores), "var": variance, "scores": scores,
                "loops": int(record["loop_completions"]), "completions": int(record["completions"]),
            })
    merged = {}
    for key, runs in cells.items():
        merged[key] = {
            "acc": sum(run["acc"] for run in runs) / len(runs),
            "se": math.sqrt(float(sum(run["var"] for run in runs))) / len(runs),
            "each": [run["acc"] for run in runs],
            "loops": Fraction(sum(run["loops"] for run in runs), sum(run["completions"] for run in runs)),
        }
    rollouts = {}
    for row in csv.DictReader((DATA / "e1_rollouts.csv").open(encoding="utf-8")):
        rollouts.setdefault(row["run"], []).append({name: float(value) for name, value in row.items() if name != "run"})
    for series in rollouts.values():
        assert [int(row["rollout"]) for row in series] == list(range(1, 801))
    return merged, rollouts


def render_e1(merged, rollouts, macros):
    base = merged[("base", "", 0, "math500")]
    math_cell = lambda objective, seed, rollout: merged.get((objective, seed, rollout, "math500"))
    finals = {seed: math_cell("GRPO", seed, 800)["acc"] for seed in SEEDS}
    changes = [float(finals[seed] - base["acc"]) for seed in SEEDS]
    mean, low, high = seed_interval(changes)
    drpo = [math_cell("DRPO", "11", rollout)["acc"] - base["acc"] for rollout in (200, 400, 600, 800)]
    # The prose in main.tex states these orderings in words.
    assert all(change < 0 for change in changes) and all(gain > 0 for gain in drpo)
    for seed in SEEDS:
        saved = [math_cell("GRPO", seed, rollout)["acc"] for rollout in (200, 400, 600, 800) if math_cell("GRPO", seed, rollout)]
        assert saved == sorted(saved, reverse=True) and len(set(saved)) == len(saved)
    assert math_cell("GRPO", "11", 200) is None and math_cell("GRPO", "11", 400) is None

    def reward(run, first, last):
        return statistics.fmean(row["reward_mean"] for row in rollouts[run][first - 1:last])

    for seed in SEEDS:
        assert reward(f"grpo-s{seed}", 701, 800) < reward(f"grpo-s{seed}", 101, 200)
    macros.update({
        "EOneMathBase": fixed(base["acc"], 4),
        "EOneMathGRPOEarlyTwentyTwo": fixed(math_cell("GRPO", "22", 200)["acc"], 4),
        "EOneMathGRPOEarlyThirtyThree": fixed(math_cell("GRPO", "33", 200)["acc"], 4),
        "EOneMathGRPODeficitMin": fixed(min(-change for change in changes), 4),
        "EOneMathGRPODeficitMax": fixed(max(-change for change in changes), 4),
        "EOneMathGRPODeficitMean": fixed(-mean, 4),
        "EOneMathGRPOChangeLow": tex(fixed(low, 2, sign=True)),
        "EOneMathGRPOChangeHigh": tex(fixed(high, 2, sign=True)),
        "EOneMathDRPOGainMin": fixed(100 * min(drpo), 1),
        "EOneMathDRPOGainMax": fixed(100 * max(drpo), 1),
        "EOneLoopBase": fixed(100 * base["loops"], 1) + r"\%",
    })
    for seed in SEEDS:
        macros["EOneMathGRPOEnd" + SEED_WORDS[seed]] = fixed(finals[seed], 4)
        macros["EOneLoopGRPO" + SEED_WORDS[seed]] = fixed(100 * math_cell("GRPO", seed, 800)["loops"], 1) + r"\%"
        macros["EOneRewardEarly" + SEED_WORDS[seed]] = fixed(reward(f"grpo-s{seed}", 101, 200), 3)
        macros["EOneRewardLate" + SEED_WORDS[seed]] = fixed(reward(f"grpo-s{seed}", 701, 800), 3)

    def cell(objective, seed, rollout, bench="math500", error=True):
        entry = merged.get((objective, seed, rollout, bench))
        if entry is None:
            return "--"
        text = fixed(entry["acc"], 4) + (f" $\\pm$ {entry['se']:.4f}" if error else "")
        return text + (r"$^{\dagger}$" if len(entry["each"]) > 1 else "")

    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{4}{c}{MATH-500 avg@4 at rollout} & \multicolumn{2}{c}{AIME avg@16 at 800} \\",
             r"\cmidrule(lr){2-5}\cmidrule(l){6-7}", r"Run & 200 & 400 & 600 & 800 & 2024 & 2025 \\", r"\midrule",
             r"Frozen base (no training) & \multicolumn{4}{c}{" + cell("base", "", 0) + "} & "
             + cell("base", "", 0, "aime24", False) + " & " + cell("base", "", 0, "aime25", False) + r" \\"]
    for objective, seed in [("GRPO", seed) for seed in SEEDS] + [("DRPO", "11")]:
        row = [f"{objective}, seed {seed}"] + [cell(objective, seed, rollout) for rollout in (200, 400, 600, 800)]
        row += [cell(objective, seed, 800, bench, False) for bench in ("aime24", "aime25")]
        table.append(" & ".join(row) + r" \\")
    table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e1_table.tex", "\n".join(table))

    summary = []
    for run, label in [("grpo-s11", "GRPO, seed 11"), ("grpo-s22", "GRPO, seed 22"), ("grpo-s33", "GRPO, seed 33"), ("drpo-s11", "DRPO, seed 11")]:
        means = [row["parity_absdiff_mean"] for row in rollouts[run]]
        peaks = [row["parity_absdiff_max"] for row in rollouts[run]]
        summary.append((label, means, peaks))
    parity = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrr@{}}", r"\toprule",
              r" & \multicolumn{3}{c}{Mean over tokens} & \multicolumn{3}{c}{Maximum over tokens} \\",
              r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
              r"Run & median & 95th pct. & largest & median & 95th pct. & largest \\", r"\midrule"]
    for label, means, peaks in summary:
        parity.append(" & ".join([label, f"{statistics.median(means):.4f}", f"{quantile(means, 0.95):.4f}", f"{max(means):.4f}",
                                  f"{statistics.median(peaks):.2f}", f"{quantile(peaks, 0.95):.2f}", f"{max(peaks):.2f}"]) + r" \\")
    parity.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e1_parity_table.tex", "\n".join(parity))
    medians = [statistics.median(means) for _, means, _ in summary]
    macros.update({
        "EOneParityChecks": f"{sum(len(means) for _, means, _ in summary):,}".replace(",", "{,}"),
        "EOneParityMedianMin": f"{min(medians):.4f}", "EOneParityMedianMax": f"{max(medians):.4f}",
        "EOneParityMeanLargest": f"{max(max(means) for _, means, _ in summary):.3f}",
        "EOneParityTokenLargest": f"{max(max(peaks) for _, _, peaks in summary):.1f}",
    })


def load_e2():
    data = json.loads((DATA / "e2_curves.json").read_text(encoding="utf-8"))
    assert data["checkpoints"] == [50, 100, 150, 200, 250, 300] and data["primary_endpoint"] == "HPSv3 at checkpoint 300"
    for metric in data["metrics"].values():
        mean, low, high = seed_interval([metric["deltas_vs_base"][seed][-1] for seed in SEEDS])
        stored = metric["endpoint_delta"]
        assert max(abs(mean - stored["mean"]), abs(low - stored["ci95_lo"]), abs(high - stored["ci95_hi"])) < 1e-5
    return data


def render_e2(data, macros):
    rows = []
    for name, label in [("HPSv3", "HPSv3"), ("ImageReward", "ImageReward"), ("PickScore", "PickScore"), ("Composition", "Composition (VQAScore)")]:
        metric = data["metrics"][name]
        mean, low, high = seed_interval([metric["deltas_vs_base"][seed][-1] for seed in SEEDS])
        final = statistics.fmean(metric["levels"][seed][-1] for seed in SEEDS)
        relative = "+" + fixed(100 * mean / metric["base"], 1) + r"\%" if name == "Composition" else "--"
        rows.append([label, tex(fixed(metric["base"], 4)), fixed(final, 4), fixed(mean, 4, sign=True),
                     f"[{fixed(low, 4, sign=True)}, {fixed(high, 4, sign=True)}]", relative])
    guard = data["diversity_guard"]
    late = seed_interval([guard["per_seed"][seed]["300"] for seed in SEEDS])
    early = seed_interval([guard["per_seed"][seed]["50"] for seed in SEEDS])
    assert all(guard["per_seed"][seed][step] < guard["investigation_trigger_pct"] for seed in SEEDS for step in ("50", "300"))
    rows.append(["LPIPS diversity", fixed(guard["base_mean_lpips"], 4), "--", "--",
                 f"[{tex(fixed(late[1], 2))}\\%, {tex(fixed(late[2], 2))}\\%]", tex(fixed(late[0], 2)) + r"\%"])
    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrr@{}}", r"\toprule",
             r"Metric & Base & Rollout 300 & $\Delta$ score & 95\% interval & $\Delta$ relative \\", r"\midrule"]
    table.extend(" & ".join(row) + r" \\" for row in rows)
    table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e2_table.tex", "\n".join(table))
    hps = data["metrics"]["HPSv3"]
    gain = seed_interval([hps["deltas_vs_base"][seed][-1] for seed in SEEDS])
    first = statistics.fmean(hps["deltas_vs_base"][seed][0] for seed in SEEDS)
    macros.update({
        "ETwoHPSGain": fixed(gain[0], 4), "ETwoHPSLow": fixed(gain[1], 4), "ETwoHPSHigh": fixed(gain[2], 4),
        "ETwoDiversityChange": tex(fixed(late[0], 2)) + r"\%",
        "ETwoDiversityLow": tex(fixed(late[1], 2)) + r"\%", "ETwoDiversityHigh": tex(fixed(late[2], 2)) + r"\%",
        "ETwoDiversityEarly": tex(fixed(early[0], 2)) + r"\%",
        "ETwoHPSEarlyShare": fixed(100 * first / gain[0], 0) + r"\%",
        "ETwoDiversityEarlyShare": fixed(100 * early[0] / late[0], 0) + r"\%",
    })


def load_e4():
    registered = json.loads((DATA / "e4v2_analysis_output.json").read_text(encoding="utf-8"))
    earlier = json.loads((DATA / "e4_paired_analysis.json").read_text(encoding="utf-8"))
    archive = json.loads((DATA / "e4_trajectories.json").read_text(encoding="utf-8"))
    assert registered["primary"] == {"checkpoint": "checkpoint-300", "key": "hpsv3_root_conditioned",
                                     "verdict": "inconclusive at three seed pairs (seed-level 95% interval includes zero)"}
    assert earlier["primary_endpoint"] == "hpsv3_root_conditioned"
    return registered, earlier, archive


def render_e4(registered, earlier, archive, macros):
    key = "hpsv3_root_conditioned"
    primary = registered["contrasts"]["checkpoint-300/" + key]["seed_level"]
    mean, low, high = seed_interval([primary["per_seed"][seed] for seed in SEEDS])
    assert max(abs(mean - primary["mean"]), abs(low - primary["ci95"][0]), abs(high - primary["ci95"][1])) < 1e-9
    excluding = sum(1 for contrast in registered["contrasts"].values() if contrast["seed_level"]["ci95"][0] > 0 or contrast["seed_level"]["ci95"][1] < 0)
    base = registered["base"]["means"][key]
    runs = sorted(registered["trajectories"])
    ends = {run: registered["trajectories"][run][key]["checkpoint-300"] for run in runs}
    assert len(runs) == 6 and all(end > base for end in ends.values()) and not any(flag["collapsed"] for flag in registered["collapse"].values())
    assert excluding == 0
    old = next(row for row in earlier["contrasts"] if row["checkpoint"] == "checkpoint-300" and row["key"] == key)["per_training_seed_mean"]
    old_mean, old_low, old_high = seed_interval([old[seed] for seed in SEEDS])
    stored = next(row for row in archive["seed_intervals"] if row["checkpoint"] == "checkpoint-300")
    assert max(abs(old_mean - stored["mean"]), abs(old_low - stored["t_interval"][0]), abs(old_high - stored["t_interval"][1])) < 1e-9
    old_base = archive["trajectories"]["base"]["base"][key]
    below = [run for run, points in archive["trajectories"].items() if run != "base" and points["checkpoint-300"][key] < old_base]
    assert len(below) == 2 and len(archive["trajectories"]) == 7

    def level_row(label, scope):
        values = [ends[f"{scope}_s{seed}"] for seed in SEEDS]
        return " & ".join([label] + [fixed(value, 2) for value in values] + [fixed(statistics.fmean(values), 2), "--"]) + r" \\"

    contrast = [tex(fixed(primary["per_seed"][seed], 2, sign=True)) for seed in SEEDS]
    interval = f"[{tex(fixed(low, 2, sign=True))}, {tex(fixed(high, 2, sign=True))}]"
    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrr@{}}", r"\toprule",
             r" & Seed 11 & Seed 22 & Seed 33 & Mean & 95\% interval \\", r"\midrule",
             r"Frozen base (no training) & \multicolumn{4}{c}{" + fixed(base, 2) + r"} & -- \\",
             level_row("Root scope", "prompt"), level_row("Rewrite scope", "rewrite"),
             r"\midrule",
             " & ".join(["Root scope minus rewrite scope"] + contrast + [tex(fixed(mean, 2, sign=True)), interval]) + r" \\",
             r"\bottomrule", r"\end{tabularx}", ""]
    write(BUNDLE / "e4_table.tex", "\n".join(table))
    macros.update({
        "EFourVTwoMean": tex(fixed(mean, 2, sign=True)), "EFourVTwoLow": tex(fixed(low, 2, sign=True)), "EFourVTwoHigh": tex(fixed(high, 2, sign=True)),
        "EFourVTwoHalfWidth": fixed((high - low) / 2, 2),
        "EFourVTwoBase": fixed(base, 2), "EFourVTwoEndMin": fixed(min(ends.values()), 2), "EFourVTwoEndMax": fixed(max(ends.values()), 2),
        "EFourVTwoGainMin": fixed(min(ends.values()) - base, 1), "EFourVTwoGainMax": fixed(max(ends.values()) - base, 1),
        "EFourVTwoIntervals": str(len(registered["contrasts"])),
        "EFourEarlierLow": tex(fixed(old_low, 2, sign=True)), "EFourEarlierHigh": tex(fixed(old_high, 2, sign=True)),
    })
    for seed in SEEDS:
        macros["EFourVTwoContrast" + SEED_WORDS[seed]] = tex(fixed(primary["per_seed"][seed], 2, sign=True))


def render_e0(macros):
    data = json.loads((DATA / "e0_parity.json").read_text(encoding="utf-8"))
    assert data["checks_per_cell"] == 1 and sum(len(run["checks"]) for run in data["runs"]) == 15
    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}lXrrrr@{}}", r"\toprule",
             r" & & \multicolumn{2}{c}{Before first update} & \multicolumn{2}{c}{After publication} \\",
             r"\cmidrule(lr){3-4}\cmidrule(l){5-6}", r"Handler & Recipe and topology & max & mean & max & mean \\", r"\midrule"]
    family = None
    for run in sorted(data["runs"], key=lambda run: (run["family"] != "diffusion", run["handler"].startswith("none"), run["handler"])):
        if run["family"] != family:
            family = run["family"]
            geometry = "two samples per prompt" if family == "diffusion" else "8 GPUs, 256 new tokens"
            table.append(r"\multicolumn{6}{@{}l}{" + family.capitalize() + f" smoke runs ({geometry})" + r"} \\")
        checks = {check["context"]: check for check in run["checks"]}
        pair = lambda name: [sci(checks[name]["absdiff_max"]), sci(checks[name]["absdiff_mean"])] if name in checks else ["--", "--"]
        number = (lambda name: [f"{checks[name]['absdiff_max']:.3f}", f"{checks[name]['absdiff_mean']:.4f}"]) if family == "autoregressive" else pair
        handler = "Train-side engine" if run["handler"].startswith("none") else r"\texttt{" + run["handler"] + "}"
        recipe = r"\texttt{" + run["recipe"].split(" ")[0].replace("_", r"\_") + "}" + ("".join(" " + word for word in run["recipe"].split(" ")[1:])) + "; " + run["topology"]
        table.append(" & ".join([handler, recipe] + number("before_first_update") + number("after_publication")) + r" \\")
    table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e0_parity_table.tex", "\n".join(table))
    diffusion = [run for run in data["runs"] if run["family"] == "diffusion"]
    before = [check["absdiff_max"] for run in diffusion for check in run["checks"] if check["context"] == "before_first_update"]
    after = [check["absdiff_max"] for run in diffusion for check in run["checks"] if check["context"] == "after_publication"]
    assert len(before) == 7 and len(after) == 5
    smoke = next(run for run in data["runs"] if run["family"] == "autoregressive")["checks"]
    macros.update({
        "EZeroDiffusionBeforeLargest": sci(max(before)), "EZeroDiffusionAfterLargest": sci(max(after)),
        "EZeroARBeforeMean": f"{next(check for check in smoke if check['context'] == 'before_first_update')['absdiff_mean']:.4f}",
        "EZeroSplitOverlap": str(data["split_overlap"]["shared_prompts_after_normalization"]),
    })


def render_macros(macros):
    names = set(re.findall(r"\\newcommand\{\\(\w+)\}", EARLIER_MACROS.read_text(encoding="utf-8")))
    assert not names & set(macros), sorted(names & set(macros))
    assert all(re.fullmatch(r"[A-Za-z]+", name) for name in macros)
    write(BUNDLE / "macros.tex", HEADER + "".join("\\newcommand{\\" + name + "}{" + value + "}\n" for name, value in macros.items()))


