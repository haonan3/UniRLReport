def save_manifest(versions):
    files = sorted(path for path in BUNDLE.rglob("*") if path.is_file() and path.name not in ("manifest.json", "checksums.sha256", "generate.py") and "__pycache__" not in path.parts)
    hashes = {path.relative_to(BUNDLE).as_posix(): digest(path) for path in files}
    generator = Path(__file__).resolve()
    manifest = {
        "schema_version": 1,
        "evidence_tier": "exported_run_outputs_see_readme_for_each_part",
        "generated_on": "2026-10-14",
        "generator": generator.relative_to(ROOT).as_posix(), "generator_sha256": digest(generator),
        "versions": versions,
        "reproduction": "python3 " + generator.relative_to(ROOT).as_posix(),
        "note": "Hashes preserve this bundle; they do not verify the experiment storage the data files were exported from.",
        "sha256": hashes,
    }
    write(BUNDLE / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    write(BUNDLE / "checksums.sha256", "".join(value + "  " + key + "\n" for key, value in hashes.items()))


def check():
    manifest = json.loads((BUNDLE / "manifest.json").read_text(encoding="utf-8"))
    mismatches = [name for name, expected in manifest["sha256"].items() if not (BUNDLE / name).is_file() or digest(BUNDLE / name) != expected]
    if digest(Path(__file__)) != manifest["generator_sha256"]:
        mismatches.append("generator")
    if mismatches:
        raise SystemExit("Checksum mismatch: " + ", ".join(mismatches))
    print(f"Verified {len(manifest['sha256'])} bundle files and generator hash.")


