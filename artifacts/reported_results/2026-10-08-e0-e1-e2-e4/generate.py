def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, content):
    path.write_text(content, encoding="utf-8")


def fixed(value, digits, sign=False):
    # Fractions are rounded exactly, so a value on a rounding boundary does not depend on its float form.
    exact = Decimal(value.numerator) / Decimal(value.denominator) if isinstance(value, Fraction) else Decimal(repr(float(value)))
    text = str(exact.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_EVEN))
    return ("+" if sign and exact >= 0 else "") + text


def tex(text):
    return text.replace("-", "$-$", 1) if text.startswith("-") else text


def sci(value):
    mantissa, exponent = f"{value:.1e}".split("e")
    return f"${mantissa}\\times10^{{{int(exponent)}}}$"


def seed_interval(values):
    mean = statistics.fmean(values)
    half = T_975_DF2 * statistics.stdev(values) / math.sqrt(len(values))
    return mean, mean - half, mean + half


def quantile(values, q):
    ordered = sorted(values)
    position = q * (len(ordered) - 1)
    low = int(position)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (position - low)


def run_id(objective, seed):
    return f"{objective.lower()}-s{seed}"


def label(objective, seed):
    return f"{objective}, seed 11, rerun" if (objective, seed) == RERUN else f"{objective}, seed {seed}"


def full_blocks(values, size=25):
    # A run that ended mid-block, as the GRPO seed 11 rerun did at rollout 518, is summarized up to its last full block.
    return values[: len(values) // size * size].reshape(-1, size)


def thousands(value):
    return f"{round(value):,}".replace(",", "{,}")


def rank_p(high, low):
    # Exact one-sided p of the rank sum of `high` over every way to split the pooled values; ties share ranks.
    pooled = sorted(high + low)
    rank = {value: Fraction(sum(i + 1 for i, other in enumerate(pooled) if other == value), pooled.count(value)) for value in pooled}
    observed = sum(rank[value] for value in high)
    sums = [sum(combo) for combo in itertools.combinations([rank[value] for value in high + low], len(high))]
    return Fraction(sum(1 for total in sums if total >= observed), len(sums))


def load_e1():
    evaluations = list(csv.DictReader((DATA / "e1_evaluations.csv").open(encoding="utf-8")))
    limits = {(row["tag"], row["benchmark"]): {name: int(value) for name, value in row.items() if name not in ("tag", "benchmark")}
              for row in csv.DictReader((DATA / "e1_token_limit.csv").open(encoding="utf-8"))}
    cells = {}
    for bench in ("math500", "aime24", "aime25"):
        rows = list(csv.DictReader((DATA / f"e1_scores_{bench}.csv").open(encoding="utf-8")))
        for record in (row for row in evaluations if row["benchmark"] == bench):
            k = int(record["samples_per_prompt"])
            scores = [Fraction(row[record["tag"]]) for row in rows]
            assert len(scores) == int(record["prompts"]) == int(record["prompts_scored"]) and record["errors"] == "0"
            variance = sum(score * (1 - score) for score in scores) / (k - 1) / len(scores) ** 2
            key = (record["objective"], record["seed"], int(record["rollout"]), bench)
            limit = limits.pop((record["tag"], bench))
            # The regrade behind the token-limit counts reproduces this evaluation's score exactly.
            assert limit["completions"] == int(record["completions"]) and limit["correct_at_limit"] + limit["correct_elsewhere"] == sum(scores) * k
            cells.setdefault(key, []).append({
                "acc": sum(scores) / len(scores), "var": variance, "scores": scores,
                "loops": int(record["loop_completions"]), "completions": int(record["completions"]), "limit": limit,
            })
    assert not limits
    merged = {}
    for key, runs in cells.items():
        merged[key] = {
            "acc": sum(run["acc"] for run in runs) / len(runs),
            "se": math.sqrt(float(sum(run["var"] for run in runs))) / len(runs),
            "each": [run["acc"] for run in runs],
            "loops": Fraction(sum(run["loops"] for run in runs), sum(run["completions"] for run in runs)),
        }
        total = {name: sum(run["limit"][name] for run in runs) for name in ("completions", "at_limit", "correct_at_limit", "correct_elsewhere")}
        merged[key].update({
            "at_limit": Fraction(total["at_limit"], total["completions"]), "limit_answers": total["at_limit"], "limit_correct": total["correct_at_limit"],
            # Accuracy on the answers that stop, and accuracy with every answer at the limit counted wrong.
            "rest": Fraction(total["correct_elsewhere"], total["completions"] - total["at_limit"]),
            "strict": Fraction(total["correct_elsewhere"], total["completions"]),
        })
    rollouts = {}
    for row in csv.DictReader((DATA / "e1_rollouts.csv").open(encoding="utf-8")):
        rollouts.setdefault(row["run"], []).append({name: float(value) if value else None for name, value in row.items() if name != "run"})
    for run, series in rollouts.items():
        assert [int(row["rollout"]) for row in series] == list(range(1, RUN_ROLLOUTS[run] + 1))
    validation = {}
    for row in csv.DictReader((DATA / "e1_validation.csv").open(encoding="utf-8")):
        validation.setdefault(row["run"], {})[int(row["rollout"])] = Fraction(int(row["correct"]), int(row["completions"]))
    assert sorted(validation) == sorted(rollouts) == sorted(RUN_ROLLOUTS)
    for run, series in validation.items():
        assert sorted(series) == list(range(0, RUN_ROLLOUTS[run] + 1, 10))
    return merged, rollouts, validation


def render_e1(merged, rollouts, macros):
    base = merged[("base", "", 0, "math500")]
    math_cell = lambda objective, seed, rollout: merged.get((objective, seed, rollout, "math500"))
    finals = {seed: math_cell("GRPO", seed, 800)["acc"] for seed in SEEDS}
    changes = [float(finals[seed] - base["acc"]) for seed in SEEDS]
    mean, low, high = seed_interval(changes)
    drpo_finals = {seed: math_cell("DRPO", seed, 800)["acc"] for seed in SEEDS}
    drpo_mean, drpo_low, drpo_high = seed_interval([float(drpo_finals[seed] - base["acc"]) for seed in SEEDS])
    drpo = [math_cell("DRPO", seed, rollout)["acc"] - base["acc"] for seed in SEEDS for rollout in (200, 400, 600, 800)]
    arm_p = rank_p(list(drpo_finals.values()), list(finals.values()))
    # The prose in main.tex states these orderings in words.
    assert all(change < 0 for change in changes) and all(gain > 0 for gain in drpo)
    assert min(drpo_finals.values()) > max(finals.values()) and arm_p == Fraction(1, 20)
    for seed in SEEDS + (RERUN[1],):
        saved = [math_cell("GRPO", seed, rollout)["acc"] for rollout in (200, 400, 600, 800) if math_cell("GRPO", seed, rollout)]
        assert saved == sorted(saved, reverse=True) and len(set(saved)) == len(saved)
    assert math_cell("GRPO", "11", 200) is None and math_cell("GRPO", "11", 400) is None

    def reward(run, first, last):
        return statistics.fmean(row["reward_mean"] for row in rollouts[run][first - 1:last])

    for seed in SEEDS:
        assert reward(f"grpo-s{seed}", 701, 800) < reward(f"grpo-s{seed}", 101, 200)

    def capped(run, first, last):
        return statistics.fmean(row["trunc_ratio"] for row in rollouts[run][first - 1:last])

    share = lambda value, digits=1: fixed(100 * value, digits) + r"\%"
    grpo_ends = [math_cell("GRPO", seed, 800) for seed in SEEDS]
    assert all(cell["at_limit"] > base["at_limit"] and Fraction(cell["limit_correct"], cell["limit_answers"]) < Fraction(1, 10) for cell in grpo_ends)

    def fall_due_to_limit(seed):
        # With accuracy on the stopped answers held at its rollout-200 value, the rest of the fall is the limit's.
        early, late = math_cell("GRPO", seed, 200), math_cell("GRPO", seed, 800)
        held = (1 - late["at_limit"]) * early["rest"] + late["at_limit"] * Fraction(late["limit_correct"], late["limit_answers"])
        return (early["acc"] - held) / (early["acc"] - late["acc"])

    twenty_two = math_cell("DRPO", "22", 800)
    others_at_limit = max(math_cell("DRPO", seed, 800)["at_limit"] for seed in ("11", "33"))
    strict_drpo = {seed: math_cell("DRPO", seed, 800)["strict"] for seed in SEEDS}
    strict_grpo = {seed: math_cell("GRPO", seed, 800)["strict"] for seed in SEEDS}
    strict_p = rank_p(list(strict_drpo.values()), list(strict_grpo.values()))
    # The prose in main.tex states each of these in words.
    assert twenty_two["at_limit"] > Fraction(1, 2) > Fraction(1, 10) > max(math_cell("DRPO", "22", rollout)["at_limit"] for rollout in (200, 400, 600))
    assert strict_drpo["22"] < min(base["strict"], min(strict_grpo.values())) and strict_p == Fraction(7, 20)
    for rollout in (200, 400, 600):
        grpo_cells = [math_cell("GRPO", seed, rollout) for seed in SEEDS + (RERUN[1],) if math_cell("GRPO", seed, rollout)]
        for key in ("acc", "strict"):
            assert min(math_cell("DRPO", seed, rollout)[key] for seed in SEEDS) > max(cell[key] for cell in grpo_cells)
    assert capped("drpo-s22", 301, 800) > 0.8 > 0.3 > max(capped("drpo-s11", 301, 800), capped("drpo-s33", 301, 800))
    macros.update({
        "EOneMathBase": fixed(base["acc"], 4),
        "EOneMathGRPOEarlyTwentyTwo": fixed(math_cell("GRPO", "22", 200)["acc"], 4),
        "EOneMathGRPOEarlyThirtyThree": fixed(math_cell("GRPO", "33", 200)["acc"], 4),
        "EOneMathGRPODeficitMin": fixed(min(-change for change in changes), 4),
        "EOneMathGRPODeficitMax": fixed(max(-change for change in changes), 4),
        "EOneMathGRPODeficitMean": fixed(-mean, 4),
        "EOneMathGRPOChangeLow": tex(fixed(low, 2, sign=True)),
        "EOneMathGRPOChangeHigh": tex(fixed(high, 2, sign=True)),
        "EOneMathDRPOGainMin": fixed(100 * min(drpo), 1),
        "EOneMathDRPOGainMax": fixed(100 * max(drpo), 1),
        "EOneMathDRPOChangeLow": tex(fixed(drpo_low, 2, sign=True)),
        "EOneMathDRPOChangeHigh": tex(fixed(drpo_high, 2, sign=True)),
        "EOneArmRankP": fixed(arm_p, 2),
        "EOneLimitBase": share(base["at_limit"]),
        "EOneLimitCorrectGRPOMax": share(max(Fraction(cell["limit_correct"], cell["limit_answers"]) for cell in grpo_ends)),
        "EOneLimitGRPOTwentyTwoEarly": share(math_cell("GRPO", "22", 200)["at_limit"]), "EOneLimitGRPOThirtyThreeEarly": share(math_cell("GRPO", "33", 200)["at_limit"]),
        "EOneRestGRPOTwentyTwoEarly": fixed(math_cell("GRPO", "22", 200)["rest"], 3), "EOneRestGRPOTwentyTwoEnd": fixed(math_cell("GRPO", "22", 800)["rest"], 3),
        "EOneRestGRPOThirtyThreeEarly": fixed(math_cell("GRPO", "33", 200)["rest"], 3), "EOneRestGRPOThirtyThreeEnd": fixed(math_cell("GRPO", "33", 800)["rest"], 3),
        "EOneLimitShareOfFallTwentyTwo": share(fall_due_to_limit("22"), 0), "EOneLimitShareOfFallThirtyThree": share(fall_due_to_limit("33"), 0),
        "EOneLimitDRPOTwentyTwo": share(twenty_two["at_limit"]),
        "EOneLimitDRPOTwentyTwoMiddle": share(math_cell("DRPO", "22", 400)["at_limit"]), "EOneLimitDRPOTwentyTwoEarlier": share(math_cell("DRPO", "22", 600)["at_limit"]),
        "EOneLimitDRPOOthersMax": share(others_at_limit),
        "EOneLimitCorrectDRPOTwentyTwo": share(Fraction(twenty_two["limit_correct"], twenty_two["limit_answers"])),
        "EOneStrictArmRankP": fixed(strict_p, 2),
        "EOneCapDRPOTwentyTwo": share(capped("drpo-s22", 301, 800)),
        "EOneMathGRPORerunEarly": fixed(math_cell(*RERUN, 200)["acc"], 4), "EOneMathGRPORerunMiddle": fixed(math_cell(*RERUN, 400)["acc"], 4),
    })
    for seed in SEEDS:
        macros["EOneMathGRPOEnd" + SEED_WORDS[seed]] = fixed(finals[seed], 4)
        macros["EOneMathDRPOEnd" + SEED_WORDS[seed]] = fixed(drpo_finals[seed], 4)
        macros["EOneLimitGRPO" + SEED_WORDS[seed]] = share(math_cell("GRPO", seed, 800)["at_limit"])
        macros["EOneStrictGRPO" + SEED_WORDS[seed]] = fixed(strict_grpo[seed], 4)
        macros["EOneStrictDRPO" + SEED_WORDS[seed]] = fixed(strict_drpo[seed], 4)
        macros["EOneRewardEarly" + SEED_WORDS[seed]] = fixed(reward(f"grpo-s{seed}", 101, 200), 3)
        macros["EOneRewardLate" + SEED_WORDS[seed]] = fixed(reward(f"grpo-s{seed}", 701, 800), 3)

    def cell(objective, seed, rollout, bench="math500", error=True):
        entry = merged.get((objective, seed, rollout, bench))
        if entry is None:
            return "--"
        text = fixed(entry["acc"], 4) + (f" $\\pm$ {entry['se']:.4f}" if error else "")
        return text + (r"$^{\dagger}$" if len(entry["each"]) > 1 else "")

    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{4}{c}{MATH-500 avg@4 at rollout} & \multicolumn{2}{c}{AIME avg@16 at 800} \\",
             r"\cmidrule(lr){2-5}\cmidrule(l){6-7}", r"Run & 200 & 400 & 600 & 800 & 2024 & 2025 \\", r"\midrule",
             r"Frozen base (no training) & \multicolumn{4}{c}{" + cell("base", "", 0) + "} & "
             + cell("base", "", 0, "aime24", False) + " & " + cell("base", "", 0, "aime25", False) + r" \\"]
    for objective, seed in TABLE_RUNS:
        row = [label(objective, seed)] + [cell(objective, seed, rollout) for rollout in (200, 400, 600, 800)]
        row += [cell(objective, seed, 800, bench, False) for bench in ("aime24", "aime25")]
        table.append(" & ".join(row) + r" \\")
    table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e1_table.tex", "\n".join(table))

    summary = []
    for objective, seed in TABLE_RUNS:
        means = [row["parity_absdiff_mean"] for row in rollouts[run_id(objective, seed)]]
        peaks = [row["parity_absdiff_max"] for row in rollouts[run_id(objective, seed)]]
        summary.append((label(objective, seed), means, peaks))
    parity = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrr@{}}", r"\toprule",
              r" & \multicolumn{3}{c}{Mean over tokens} & \multicolumn{3}{c}{Maximum over tokens} \\",
              r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
              r"Run & median & 95th pct. & largest & median & 95th pct. & largest \\", r"\midrule"]
    for name, means, peaks in summary:
        parity.append(" & ".join([name, f"{statistics.median(means):.4f}", f"{quantile(means, 0.95):.4f}", f"{max(means):.4f}",
                                  f"{statistics.median(peaks):.2f}", f"{quantile(peaks, 0.95):.2f}", f"{max(peaks):.2f}"]) + r" \\")
    parity.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e1_parity_table.tex", "\n".join(parity))
    medians = [statistics.median(means) for _, means, _ in summary]
    macros.update({
        "EOneParityChecks": f"{sum(len(means) for _, means, _ in summary):,}".replace(",", "{,}"),
        "EOneParityMedianMin": f"{min(medians):.4f}", "EOneParityMedianMax": f"{max(medians):.4f}",
        "EOneParityMeanLargest": f"{max(max(means) for _, means, _ in summary):.3f}",
        "EOneParityTokenLargest": f"{max(max(peaks) for _, _, peaks in summary):.1f}",
    })


def render_e1_supplement(merged, rollouts, validation, macros):
    math_cell = lambda objective, seed, rollout: merged.get((objective, seed, rollout, "math500"))
    base = merged[("base", "", 0, "math500")]["acc"]

    # Internal validation and the saved checkpoint it selects in each run.
    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{3}{c}{Validation accuracy} & \multicolumn{3}{c}{Validation-selected checkpoint} & Final \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(l){8-8}",
             r"Run & before & highest (rollout) & at 800 & rollout & validation & MATH-500 & MATH-500 \\", r"\midrule"]
    peaks, picks, rows = {}, {}, {}
    for objective, seed in E1_RUNS:
        series = validation[run_id(objective, seed)]
        peak = max(series, key=lambda rollout: (series[rollout], -rollout))
        ranked = sorted(SAVED, key=lambda rollout: series[rollout], reverse=True)
        assert series[ranked[0]] > series[ranked[1]] and series[800] < series[peak] and peak <= 400
        peaks[(objective, seed)], picks[(objective, seed)] = peak, ranked[0]
        entry = math_cell(objective, seed, ranked[0])
        rows[(objective, seed)] = " & ".join([label(objective, seed), fixed(series[0], 4), f"{fixed(series[peak], 4)} ({peak})", fixed(series[800], 4), str(ranked[0]),
                                              fixed(series[ranked[0]], 4), fixed(entry["acc"], 4) if entry else "lost",
                                              fixed(math_cell(objective, seed, 800)["acc"], 4) + (r"$^{\dagger}$" if len(math_cell(objective, seed, 800)["each"]) > 1 else "")]) + r" \\"
    rerun = validation[run_id(*RERUN)]
    rerun_peak = max(rerun, key=lambda rollout: (rerun[rollout], -rollout))
    rerun_pick = max((200, 400), key=lambda rollout: rerun[rollout])
    rows[RERUN] = " & ".join([label(*RERUN), fixed(rerun[0], 4), f"{fixed(rerun[rerun_peak], 4)} ({rerun_peak})", "--", str(rerun_pick), fixed(rerun[rerun_pick], 4),
                              fixed(math_cell(*RERUN, rerun_pick)["acc"], 4), "--"]) + r" \\"
    table.extend(rows[run] for run in TABLE_RUNS)
    table.extend([r"\bottomrule", r"\end{tabularx}", ""])
    write(BUNDLE / "e1_validation_table.tex", "\n".join(table))
    value = lambda objective, seed, rollout: validation[run_id(objective, seed)][rollout]
    eleven = validation["grpo-s11"]
    # The prose in main.tex states these selections and orderings in words.
    assert picks == {**{run: 200 for run in E1_RUNS}, ("DRPO", "11"): 400} and sum(1 for run in E1_RUNS if peaks[run] not in SAVED) == 4
    assert eleven[800] <= eleven[0] and min(eleven[200], eleven[400]) > max(eleven[600], eleven[800])
    assert all(math_cell(objective, seed, picks[(objective, seed)])["acc"] > max(base, math_cell(objective, seed, 800)["acc"]) for objective, seed in E1_RUNS if (objective, seed) != ("GRPO", "11"))
    grpo_start, grpo_end = [value("GRPO", seed, 0) for seed in SEEDS], [value("GRPO", seed, 800) for seed in SEEDS]
    drpo_end, drpo_peak = [value("DRPO", seed, 800) for seed in SEEDS], [value("DRPO", seed, peaks[("DRPO", seed)]) for seed in SEEDS]
    assert max(value("GRPO", seed, peaks[("GRPO", seed)]) for seed in SEEDS) < min(drpo_end) < max(drpo_end) < min(drpo_peak)
    macros.update({
        "EOneValidGRPOElevenStart": fixed(eleven[0], 3), "EOneValidGRPOElevenPeak": fixed(eleven[peaks[("GRPO", "11")]], 3), "EOneValidGRPOElevenEnd": fixed(eleven[800], 3),
        "EOneValidGRPOStartMin": fixed(min(grpo_start), 3), "EOneValidGRPOStartMax": fixed(max(grpo_start), 3),
        "EOneValidGRPOEndMin": fixed(min(grpo_end), 3), "EOneValidGRPOEndMax": fixed(max(grpo_end), 3),
        "EOneValidDRPOEndMin": fixed(min(drpo_end), 3), "EOneValidDRPOEndMax": fixed(max(drpo_end), 3),
        "EOneValidDRPOPeakMin": fixed(min(drpo_peak), 3), "EOneValidDRPOPeakMax": fixed(max(drpo_peak), 3),
    })
    for seed in SEEDS:
        macros["EOneMathDRPOSelected" + SEED_WORDS[seed]] = fixed(math_cell("DRPO", seed, picks[("DRPO", seed)])["acc"], 4)
    # The rerun reads the original's prompts in the same order, so where it runs above or below the original measures how far the two runs part.
    evals = [rollout for rollout in sorted(rerun) if rollout > 0]
    above_to = max(rollout for rollout in evals if rerun[rollout] > eleven[rollout])
    above_from = min(start for start in evals if all(rerun[rollout] > eleven[rollout] for rollout in evals if start <= rollout <= above_to))
    below, last = [rollout for rollout in evals if rollout > above_to], evals[-1]
    assert above_from <= 110 and above_to >= 400 and below and all(rerun[rollout] < eleven[rollout] for rollout in below)
    assert rerun[400] > max(value("GRPO", seed, 400) for seed in SEEDS) and rerun[last] < min(value("GRPO", seed, last) for seed in SEEDS)
    macros.update({
        "EOneRerunAboveFrom": str(above_from), "EOneRerunAboveTo": str(above_to), "EOneRerunBelowFrom": str(below[0]), "EOneRerunLastEval": str(last),
        "EOneRerunEnd": str(RUN_ROLLOUTS[run_id(*RERUN)]),
        "EOneValidRerunFour": fixed(rerun[400], 3), "EOneValidGRPOElevenFour": fixed(eleven[400], 3),
        "EOneValidRerunLast": fixed(rerun[last], 3), "EOneValidGRPOElevenLast": fixed(eleven[last], 3),
    })

    # Answers at the token limit at every evaluated checkpoint, with the final checkpoint's split.
    share = lambda entry: fixed(100 * entry["at_limit"], 1) + r"\%" if entry else "--"
    split = lambda entry: [f"{entry['limit_correct']:,} of {entry['limit_answers']:,}".replace(",", "{,}"), fixed(entry["rest"], 3), fixed(entry["strict"], 4)]
    start = merged[("base", "", 0, "math500")]
    table = [HEADER.rstrip(), r"\begin{tabularx}{\textwidth}{@{}Xrrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{4}{c}{Answers at the limit, by rollout} & \multicolumn{3}{c}{Final checkpoint} \\",
             r"\cmidrule(lr){2-5}\cmidrule(l){6-8}",
             r"Run & 200 & 400 & 600 & 800 & correct at the limit & correct elsewhere & limit counted wrong \\", r"\midrule",
             " & ".join(["Frozen base", r"\multicolumn{4}{c}{" + share(start) + "}"] + split(start)) + r" \\"]
    for objective, seed in TABLE_RUNS:
        final = math_cell(objective, seed, 800)
