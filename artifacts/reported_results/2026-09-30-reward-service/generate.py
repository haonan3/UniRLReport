def read(name: str) -> list[dict[str, str]]:
    with open(HERE / name, newline="") as handle:
        return list(csv.DictReader(handle))


def summarize(runs: list[dict[str, str]]) -> list[dict[str, str]]:
    """Mean over steady-state rollouts (rollout >= 2) of arms without the diagnostic memory flush."""
    groups: dict[tuple, list[dict[str, str]]] = defaultdict(list)
    for row in runs:
        if row["steady"] != "1" or row["flush_after_rollout"] != "0":
            continue
        key = (row["workload"], row["reward"], int(row["rows_per_rank"]), row["micros_per_rank"], row["arm"], row["overlap_impl"])
        groups[key].append(row)
    baseline = {
        key[:3]: statistics.fmean(float(r["generate_reward_s"]) for r in rows)
        for key, rows in groups.items()
        if key[4] == "baseline"
    }
    for key, rows in list(groups.items()):
        if key[4] == "overlap":
            groups[key[:5] + ("pooled",)].extend(rows)
    out = []
    for key, rows in groups.items():
        workload, reward, rows_per_rank, micros, arm, impl = key
        wall = [float(r["generate_reward_s"]) for r in rows]
        generate = [float(r["generate_s"] or r["stack_generate_s"]) for r in rows]
        mean = statistics.fmean(wall)
        out.append({
            "workload": workload, "reward": reward, "rows_per_rank": str(rows_per_rank), "micros_per_rank": micros,
            "arm": arm, "overlap_impl": impl, "rollouts": str(len(rows)), "sessions": str(len({r["session"] for r in rows})),
            "generate_reward_mean_s": f"{mean:.1f}", "generate_reward_min_s": f"{min(wall):.1f}",
            "generate_reward_max_s": f"{max(wall):.1f}", "generate_mean_s": f"{statistics.fmean(generate):.1f}",
            "exposed_reward_mean_s": f"{mean - statistics.fmean(generate):.1f}",
            "change_vs_baseline_pct": f"{100.0 * (mean / baseline[key[:3]] - 1.0):+.1f}",
            "train_mean_s": f"{statistics.fmean(float(r['train_s']) for r in rows):.1f}",
        })
    out.sort(key=lambda r: (r["workload"], r["reward"] != "editscore_8b", r["reward"], -int(r["rows_per_rank"]),
                            ARM_ORDER.index(r["arm"]), r["micros_per_rank"], r["overlap_impl"]))
    return out


def pick(summary: list[dict[str, str]], reward: str, arm: str, *, rows: str = "32", micros: str = "4") -> dict[str, str]:
    """The summary row the manuscript quotes; overlap rows pool both implementations."""
    found = [
        r for r in summary
        if r["reward"] == reward and r["arm"] == arm and r["rows_per_rank"] == rows
        and (arm in ("baseline", "request_batch_only") or r["micros_per_rank"] == micros)
    ]
    found.sort(key=lambda r: r["overlap_impl"] != "pooled")
    return found[0]


def judge_summary(trace: list[dict[str, str]]) -> list[dict[str, str]]:
    """Judge-side and rank-side aggregates of the traced rollouts, per reward and schedule."""
    rollouts: dict[tuple, list[dict[str, str]]] = defaultdict(list)
    for row in trace:
        rollouts[(row["reward"], row["arm"], row["session"], row["rollout"])].append(row)
    per_arm: dict[tuple, list[dict[str, float]]] = defaultdict(list)
    for (reward, arm, _session, _rollout), rows in rollouts.items():
        judge = [r for r in rows if r["kind"] == "judge_service"]
        waits = [r for r in rows if r["kind"] == "reward_wait"]
        service = [float(r["end_s"]) - float(r["start_s"]) for r in judge]
        first = min(float(r["recv_s"]) for r in judge)
        last = max(float(r["end_s"]) for r in judge)
        first_micro = [float(r["end_s"]) - float(r["start_s"]) for r in waits if r["index"] == "1"]
        later = [float(r["end_s"]) - float(r["start_s"]) for r in waits if r["index"] != "1"]
        per_arm[(reward, arm)].append({
            "requests": len(judge), "pairs": statistics.fmean(float(r["rows"]) for r in judge),
            "service": statistics.fmean(service), "work": sum(service), "idle": (last - first) - sum(service),
            "first_arrival": first, "last_done": last,
            "generation_end": max(float(r["end_s"]) for r in rows if r["kind"] == "generate"),
            "first_wait_max": max(first_micro), "later_wait_median": statistics.median(later) if later else float("nan"),
        })
    out = []
    for (reward, arm), items in per_arm.items():
        def mean(key: str) -> float:
            return statistics.fmean(item[key] for item in items)
        out.append({
            "reward": reward, "arm": arm, "rollouts": str(len(items)),
            "requests_per_rollout": f"{mean('requests'):.0f}", "pairs_per_request": f"{mean('pairs'):.0f}",
            "service_per_request_s": f"{mean('service'):.2f}",
            "judge_work_mean_s": f"{mean('work'):.1f}",
            "judge_work_min_s": f"{min(i['work'] for i in items):.1f}", "judge_work_max_s": f"{max(i['work'] for i in items):.1f}",
            "judge_idle_mean_s": f"{mean('idle'):.1f}", "first_arrival_s": f"{mean('first_arrival'):.1f}",
            "generation_end_s": f"{mean('generation_end'):.1f}", "last_done_s": f"{mean('last_done'):.1f}",
            "first_micro_wait_max_s": f"{mean('first_wait_max'):.1f}",
            "later_micro_wait_median_s": "" if arm == "baseline" else f"{mean('later_wait_median'):.1f}",
        })
    out.sort(key=lambda r: (r["reward"] != "editscore_8b", ARM_ORDER.index(r["arm"])))
    return out


def write_overlap_table(summary: list[dict[str, str]]) -> None:
    lines = [
        NOTE,
        "\\begin{tabularx}{\\textwidth}{@{}Xrrrr@{}}\n\\toprule\n",
        "Schedule & Rollouts & Generate + reward (s) & Range (s) & vs.\\ whole shard \\\\\n",
    ]
    for reward in ("editscore_8b", "editscore_72b", "pickscore_local"):
        lines.append("\\midrule\n\\multicolumn{5}{@{}l}{" + REWARD_LABEL[reward] + "} \\\\\n")
        for arm in ("baseline", "serial", "overlap"):
            row = pick(summary, reward, arm)
            mark = ""
            change = "--" if arm == "baseline" else row["change_vs_baseline_pct"].replace("-", "$-$").replace("+", "$+$") + "\\%"
            lines.append(
                f"{ARM_LABEL[arm]}{mark} & {row['rollouts']} & {row['generate_reward_mean_s']} & "
                f"{row['generate_reward_min_s']}--{row['generate_reward_max_s']} & {change} \\\\\n"
            )
    lines.append("\\bottomrule\n\\end{tabularx}\n")
    (HERE / "overlap_table.tex").write_text("".join(lines))


def tt(name: str) -> str:
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def write_scorers_table(scorers: list[dict[str, str]]) -> None:
    lines = [
        NOTE,
        "\\begin{tabularx}{\\textwidth}{@{}L{0.14\\textwidth}YY@{}}\n\\toprule\n",
        "Output scored & In-process backends & Reward-service scorers \\\\\n\\midrule\n",
    ]
    for modality in MODALITY_ORDER:
        cells = []
        for host in ("local", "service"):
            names = []
            for row in scorers:
                if row["modality"] != modality or row["host"] != host or row["note"].startswith("placeholder"):
                    continue
                names.append(tt(row["name"]) + ("$^{\\ast}$" if row["note"].startswith("disabled") else ""))
            cells.append(", ".join(names) if names else "--")
        lines.append(f"{MODALITY_LABEL[modality]} & {cells[0]} & {cells[1]} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabularx}\n")
    (HERE / "scorers_table.tex").write_text("".join(lines))


def write_mps_table(mps: list[dict[str, str]]) -> None:
    cells: dict[tuple[str, str, str], str] = {}
    order: list[str] = []
    for row in mps:
        if row["table"] != "homogeneous":
            continue
        if row["workload"] not in order:
            order.append(row["workload"])
        value = float(row["mps_gain_pct"])
        cells[(row["workload"], row["copies_or_size"], row["model_batch"])] = ("$+$" if value >= 0 else "$-$") + f"{abs(value):.1f}"
    lines = [
        NOTE,
        "\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n",
        " & \\multicolumn{3}{c}{Two copies} & \\multicolumn{3}{c}{Three copies} \\\\\n",
        "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}\n",
        "Scorer & $b{=}1$ & $b{=}4$ & $b{=}8$ & $b{=}1$ & $b{=}4$ & $b{=}8$ \\\\\n\\midrule\n",
    ]
    for workload in order:
        row = [cells.get((workload, copies, batch), "--") for copies in ("2", "3") for batch in ("1", "4", "8")]
        lines.append(f"{workload} & " + " & ".join(row) + " \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    (HERE / "mps_table.tex").write_text("".join(lines))


def train_seconds(runs: list[dict[str, str]], session: str, flush: str) -> str:
    """Mean train phase after a micro-batched rollout, with or without the collection pass at the rollout boundary."""
    values = [
        float(r["train_s"]) for r in runs
        if r["session"] == session and r["steady"] == "1" and r["arm"] in ("serial", "overlap") and r["flush_after_rollout"] == flush
    ]
    return f"{statistics.fmean(values):.1f}"


