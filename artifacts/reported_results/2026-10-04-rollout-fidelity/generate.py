#!/usr/bin/env python3
"""Regenerate the rollout-fidelity tables, macros and figure from the committed CSVs (see README.md)."""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
NOTE = "% Generated by artifacts/reported_results/2026-10-04-rollout-fidelity/generate.py; do not edit.\n"

STAGE_ORDER = ["main", "injection fix", "per-group canvas", "sibling packing"]
STAGE_LABEL = {
    "main": "\\texttt{main} before the fix",
    "injection fix": "+ restored it2i conditioning (\\#547)",
    "per-group canvas": "+ per-group canvas (\\#549)",
    "sibling packing": "+ sibling packing (\\#550)",
}
STRATEGY_LABEL = {
    "baseline": "Prompt-order shards (today)",
    "baseline+overlap": "Prompt-order shards, reward overlapped",
    "owner": "Prompt-order shards through the unit queue",
    "balanced": "Cost-balanced shards",
    "steal": "Cost-balanced shards with stealing",
    "steal+overlap": "Cost-balanced with stealing, reward overlapped",
}


def read(name: str) -> list[dict[str, str]]:
    with open(HERE / name, newline="") as handle:
        return list(csv.DictReader(handle))


def by_stage(arms: list[dict[str, str]]) -> dict[str, list[dict[str, str]]]:
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in arms:
        if row["micro_batch_size"] in ("", "8"):
            groups[row["stage"]].append(row)
    return groups


def num(rows: list[dict[str, str]], key: str) -> list[float]:
    return [float(r[key]) for r in rows if r[key]]


def write_it2i_table(arms: list[dict[str, str]]) -> None:
    groups = by_stage(arms)
    base = statistics.fmean(num(groups["main"], "generate_s"))
    lines = [
        NOTE,
        "\\begin{tabularx}{\\textwidth}{@{}Xrrrr@{}}\n\\toprule\n",
        "Rollout path & Rollouts & Generation (s) & vs.\\ \\texttt{main} & First-rollout reward \\\\\n\\midrule\n",
    ]
    for stage in STAGE_ORDER:
        rows = groups[stage]
        generate = num(rows, "generate_s")
        first = num([r for r in rows if r["rollout"] == "1"], "reward_mean")
        mean = statistics.fmean(generate)
        change = "--" if stage == "main" else f"$-${100.0 * (1.0 - mean / base):.0f}\\%"
        value = f"{min(first):.2f}--{max(first):.2f}" if len(first) > 1 else f"{first[0]:.2f}"
        lines.append(f"{STAGE_LABEL[stage]} & {len(rows)} & {mean:.1f} & {change} & {value} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabularx}\n")
    (HERE / "it2i_table.tex").write_text("".join(lines))


def write_layout_table(probes: list[dict[str, str]]) -> None:
    """Probe table of the token-layout check: engine and trainer context lengths, and what each probe produced."""
    lines = [
        NOTE,
        "\\begin{tabularx}{\\textwidth}{@{}Xlrrll@{}}\n\\toprule\n",
        "Probe & Path & Engine & Trainer & Layout check & $|r-1|$ \\\\\n\\midrule\n",
    ]
    for row in probes:
        deviation = row["first_update_ratio_dev"]
        if not deviation:
            shown = "--"
        elif float(deviation) == 0.0:
            shown = "$0$"
        else:
            mantissa, exponent = f"{float(deviation):.1e}".split("e")
            shown = f"${mantissa}\\times10^{{{int(exponent)}}}$"
        name = row["probe"][0].upper() + row["probe"][1:]
        lines.append(
            f"{name} & {row['workload']} & {row['engine_kv_len']} & {row['trainer_kv_len']} & "
            f"{row['layout_check']} & {shown} \\\\\n"
        )
    lines.append("\\bottomrule\n\\end{tabularx}\n")
    (HERE / "layout_table.tex").write_text("".join(lines))


def write_canvas_table(costs: list[dict[str, str]]) -> None:
    rows = [r for r in costs if r["group_rows"] == "4"]
    canvases = ["512x512", "768x768", "1024x1024"]
    lines = [
        NOTE,
        "\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\n",
        "Canvas & Image tokens & it2i, one per sample & it2i, packed & t2i, packed \\\\\n\\midrule\n",
    ]
    for canvas in canvases:
        cells = []
        for workload, packing in (("it2i", "one request per sample"), ("it2i", "packed"), ("t2i", "packed")):
            match = [r for r in rows if r["canvas"] == canvas and r["workload"] == workload and r["packing"] == packing]
            cells.append(f"{float(match[0]['seconds_per_group']):.2f}" if match else "--")
        tokens = next(r["image_tokens"] for r in rows if r["canvas"] == canvas)
        label = "$" + canvas.replace("x", "\\times") + "$"
        lines.append(label + f" & {tokens} & " + " & ".join(cells) + " \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    (HERE / "canvas_table.tex").write_text("".join(lines))


def write_longtail_table(longtail: list[dict[str, str]]) -> None:
    lines = [
        NOTE,
        "\\begin{tabularx}{\\textwidth}{@{}Xrrrr@{}}\n\\toprule\n",
        "Assignment & Rollout + reward (s) & Slowest rank (s) & Mean rank (s) & Idle \\\\\n",
    ]
    blocks = [
        ("t2i, in-process PickScore", "t2i", "pickscore_local", ["baseline", "balanced", "steal"], "pixels"),
        ("it2i, EditScore 8B on another node", "it2i", "editscore_8b",
         ["baseline", "baseline+overlap", "steal", "steal+overlap"], "pixels"),
        ("it2i, EditScore 72B on another node", "it2i", "editscore_72b", ["baseline", "steal+overlap"], "pixels"),
    ]
    longtail = [r for r in longtail if r["rollout"] == "2"]
    for title, workload, reward, strategies, cost in blocks:
        lines.append("\\midrule\n\\multicolumn{5}{@{}l}{" + title + "} \\\\\n")
        for strategy in strategies:
            rows = [
                r for r in longtail
                if r["workload"] == workload and r["reward"] == reward and r["strategy"] == strategy
                and (r["cost_model"] in ("", cost))
            ]
            if not rows:
                continue
            lines.append(
                f"{STRATEGY_LABEL[strategy]} & "
                f"{statistics.fmean(num(rows, 'rollout_score_s')):.1f} & "
                f"{statistics.fmean(num(rows, 'slowest_rank_generate_s')):.1f} & "
                f"{statistics.fmean(num(rows, 'mean_rank_generate_s')):.1f} & "
                f"{statistics.fmean(num(rows, 'idle_pct')):.0f}\\% \\\\\n"
            )
    lines.append("\\bottomrule\n\\end{tabularx}\n")
    (HERE / "longtail_table.tex").write_text("".join(lines))


def write_macros(arms: list[dict[str, str]], costs: list[dict[str, str]], longtail: list[dict[str, str]],
                 tail: list[dict[str, str]]) -> None:
    groups = by_stage(arms)
    generate = {stage: statistics.fmean(num(rows, "generate_s")) for stage, rows in groups.items()}
    post_fix = [float(r["reward_mean"]) for r in arms if r["stage"] != "main" and r["rollout"] == "1"]
    ratios = [float(r["slowest_rank_generate_s"]) / float(r["mean_rank_generate_s"]) for r in tail]

    def lt(workload: str, reward: str, strategy: str, key: str, rollout: str = "2", cost: str = "pixels") -> float:
        rows = [
            r for r in longtail
            if (r["workload"], r["reward"], r["strategy"], r["rollout"]) == (workload, reward, strategy, rollout)
            and r["cost_model"] in ("", cost)
        ]
        return float(rows[0][key])

    macros = {
        "RFMainGenerate": f"{generate['main']:.1f}",
        "RFFixGenerate": f"{generate['injection fix']:.1f}",
        "RFPackGenerate": f"{generate['sibling packing']:.1f}",
        "RFFixSaving": f"{100.0 * (1.0 - generate['injection fix'] / generate['main']):.0f}\\%",
        "RFPackSaving": f"{100.0 * (1.0 - generate['sibling packing'] / generate['per-group canvas']):.0f}\\%",
        "RFTotalSaving": f"{100.0 * (1.0 - generate['sibling packing'] / generate['main']):.0f}\\%",
        "RFMainReward": f"{float(groups['main'][0]['reward_mean']):.2f}",
        "RFFixReward": f"{float(groups['injection fix'][0]['reward_mean']):.2f}",
        "RFPostFixRewardMin": f"{min(post_fix):.2f}",
        "RFPostFixRewardMax": f"{max(post_fix):.2f}",
        "RFLongTailRollout": "2",
        "RFWorkerKv": "5938",
        "RFTrainerKv": "2263",
        "RFRatioBuggy": "5.0",
        "RFRatioHealthy": "3.4",
        "RFTailMin": f"{min(ratios):.2f}",
        "RFTailMax": f"{max(ratios):.2f}",
        "RFSmallBase": f"{lt('it2i', 'editscore_8b', 'baseline', 'rollout_score_s'):.1f}",
        "RFSmallOverlap": f"{lt('it2i', 'editscore_8b', 'baseline+overlap', 'rollout_score_s'):.1f}",
        "RFSmallSteal": f"{lt('it2i', 'editscore_8b', 'steal', 'rollout_score_s'):.1f}",
        "RFSmallBoth": f"{lt('it2i', 'editscore_8b', 'steal+overlap', 'rollout_score_s'):.1f}",
        "RFSmallBothSaving": f"{100.0 * (1.0 - lt('it2i', 'editscore_8b', 'steal+overlap', 'rollout_score_s') / lt('it2i', 'editscore_8b', 'baseline', 'rollout_score_s')):.0f}\\%",
        "RFLargeBase": f"{lt('it2i', 'editscore_72b', 'baseline', 'rollout_score_s'):.1f}",
        "RFLargeSteal": f"{lt('it2i', 'editscore_72b', 'steal+overlap', 'rollout_score_s'):.1f}",
        "RFLargeFirstBase": f"{lt('it2i', 'editscore_72b', 'baseline', 'rollout_score_s', '1'):.1f}",
        "RFLargeFirstSteal": f"{lt('it2i', 'editscore_72b', 'steal+overlap', 'rollout_score_s', '1'):.1f}",
        "RFLargeTail": f"{lt('it2i', 'editscore_72b', 'baseline', 'slowest_rank_generate_s'):.1f}",
        "RFLargeTailSteal": f"{lt('it2i', 'editscore_72b', 'steal+overlap', 'slowest_rank_generate_s'):.1f}",
        "RFTtoiBase": f"{lt('t2i', 'pickscore_local', 'baseline', 'rollout_score_s'):.1f}",
        "RFTtoiBalanced": f"{lt('t2i', 'pickscore_local', 'balanced', 'rollout_score_s'):.1f}",
        "RFTtoiIdle": f"{lt('t2i', 'pickscore_local', 'baseline', 'idle_pct'):.0f}\\%",
        "RFNaiveBalanced": f"{lt('t2i', 'pickscore_local', 'balanced', 'rollout_score_s', '2', 'rows'):.1f}",
        "RFNaiveSteal": f"{lt('t2i', 'pickscore_local', 'steal', 'rollout_score_s', '2', 'rows'):.1f}",
        "RFNaiveGap": f"{lt('t2i', 'pickscore_local', 'balanced', 'rollout_score_s', '2', 'rows') - lt('t2i', 'pickscore_local', 'balanced', 'rollout_score_s'):.0f}",
        "RFStealRecovered": f"{lt('t2i', 'pickscore_local', 'balanced', 'rollout_score_s', '2', 'rows') - lt('t2i', 'pickscore_local', 'steal', 'rollout_score_s', '2', 'rows'):.0f}",
        "RFPackedGroupEight": next(r["seconds_per_group"] for r in costs
                                   if r["workload"] == "it2i" and r["packing"] == "packed" and r["group_rows"] == "8"),
        "RFUnpackedGroupEight": next(r["seconds_per_group"] for r in costs
                                     if r["workload"] == "it2i" and r["packing"] == "one request per sample"
                                     and r["group_rows"] == "8"),
    }
    body = "".join(f"\\newcommand{{\\{name}}}{{{value}}}\n" for name, value in macros.items())
    (HERE / "macros.tex").write_text(NOTE + body)


def write_figure(arms: list[dict[str, str]]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ink, muted, bar, dot, before = "#1f2430", "#525a65", "#b0bbc6", "#256b9c", "#b65e2b"
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 9.2,
        "axes.spines.top": False, "axes.spines.right": False, "axes.spines.left": False,
        "axes.edgecolor": "#626975", "axes.linewidth": 0.65,
        "pdf.fonttype": 42, "ps.fonttype": 42,
        "savefig.facecolor": "white", "figure.facecolor": "white",
    })
    groups = by_stage(arms)
    stages = [s for s in STAGE_ORDER if s != "per-group canvas"]
    short = {"main": "main before the fix", "injection fix": "+ restored conditioning",
             "sibling packing": "+ sibling packing"}
    fig, axes = plt.subplots(1, 2, figsize=(7.25, 2.4), gridspec_kw={"width_ratios": [1.35, 1]})

    ax = axes[0]
    ys = list(range(len(stages)))[::-1]
    for y, stage in zip(ys, stages):
        value = statistics.fmean(num(groups[stage], "generate_s"))
        ax.barh(y, value, height=0.56, color=bar, zorder=3)
        ax.text(value + 1.0, y, f"{value:.1f} s", va="center", ha="left", fontsize=9, color=ink)
    ax.set_yticks(ys, [short[s] for s in stages])
    ax.set_xlim(0, 62)
    ax.set_ylim(-0.6, len(stages) - 0.4)
    ax.set_xlabel("Seconds to generate 16 edits on one rank", color=muted, fontsize=8.8)
    ax.set_title("(a) Generation", loc="left", pad=6, fontsize=9.6, fontweight="bold", color=ink)

    ax = axes[1]
    before_values = num(groups["main"], "reward_mean")
    after_values = [float(r["reward_mean"]) for r in arms if r["stage"] != "main" and r["rollout"] == "1"]
    ax.scatter([0] * len(before_values), before_values, s=42, color=before, edgecolors="white", linewidths=0.6, zorder=3)
    ax.scatter([1] * len(after_values), after_values, s=42, color=dot, edgecolors="white", linewidths=0.6, zorder=3)
    ax.annotate(f"{before_values[0]:.2f}", (0, before_values[0]), xytext=(10, -3), textcoords="offset points",
                fontsize=8.6, color=ink)
    ax.annotate(f"{min(after_values):.2f}–{max(after_values):.2f}", (1, statistics.fmean(after_values)),
                xytext=(10, -3), textcoords="offset points", fontsize=8.6, color=ink)
    ax.set_xticks([0, 1], ["before", "after"])
    ax.set_xlim(-0.5, 2.45)
    ax.set_ylim(2.0, 5.6)
    ax.tick_params(axis="x", colors=muted, labelsize=8.6, length=0)
    ax.tick_params(axis="y", colors=muted, labelsize=8.4)
    ax.spines["left"].set_visible(True)
    ax.spines["left"].set_color("#626975")
    ax.grid(axis="y", color="#d9dee6", linewidth=0.6, zorder=0)
    ax.set_axisbelow(True)
    ax.set_ylabel("EditScore of the first rollout", color=muted, fontsize=8.6)
    ax.set_title("(b) What the judge saw", loc="left", pad=6, fontsize=9.6, fontweight="bold", color=ink)

    for ax in axes:
        ax.tick_params(axis="x", colors=muted, labelsize=8.4)
    axes[0].tick_params(axis="y", length=0, labelcolor=ink, labelsize=8.8)
    axes[0].grid(axis="x", color="#d9dee6", linewidth=0.6, zorder=0)
    axes[0].set_axisbelow(True)
    fig.subplots_adjust(left=0.225, right=0.985, top=0.855, bottom=0.235, wspace=0.46)
    figures = HERE / "figures"
    figures.mkdir(exist_ok=True)
    fig.savefig(figures / "rollout_chain.pdf", metadata={"Creator": "UniRL rollout-fidelity generator", "CreationDate": None, "ModDate": None})
    fig.savefig(figures / "rollout_chain.png", dpi=200, metadata={"Software": "UniRL rollout-fidelity generator"})
    plt.close(fig)


def main() -> None:
    arms, costs = read("it2i_arms.csv"), read("canvas_cost.csv")
    probes = read("layout_check.csv")
    longtail, tail = read("longtail_arms.csv"), read("mixed_canvas_tail.csv")
    write_it2i_table(arms)
    write_layout_table(probes)
    write_canvas_table(costs)
    write_longtail_table(longtail)
    write_macros(arms, costs, longtail, tail)
    write_figure(arms)
    print(f"tables, macros and figure written to {HERE}")


if __name__ == "__main__":
    main()
